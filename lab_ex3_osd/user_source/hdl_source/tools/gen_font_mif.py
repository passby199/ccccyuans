#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
gen_font_mif.py  --  从 osd_char_lib.v 提取 16x16 点阵，生成 target_osd 用的 ERAM 字库 MIF

为什么单独做一份字库
---------------------------------------------------------------------------
hdmi_mixer 里的 osd_char_lib 是一个 case 表，被 TD 综合成 LUT 搭的分布式 ROM。
目标识别模块 target_osd 插在 enhance 之后（独立文件），如果直接再例化一个
osd_char_lib，会多出一份 LUT ROM（约 400~600 LUT），而本工程 slice 只剩
1519 个，装不下。所以改成 ERAM 字库（1 块 20K ERAM，0 LUT）——
照抄 anlogic_logo_rom.v 里已经验证过的 PH1P_LOGIC_ERAM + INIT_FILE 写法。

地址编码（10 位）
---------------------------------------------------------------------------
    addr = {char_idx[5:0], row[3:0]}
    char_idx : 0..25 = 'A'..'Z'   26..35 = '0'..'9'   36 = 空格   37 = ':'
    其余 char_idx 全部填 0（不会用到）

位序（与 osd_char_lib / hdmi_mixer 完全一致）
---------------------------------------------------------------------------
    bit15 = 最左像素 ... bit0 = 最右像素
    所以 target_osd 里 col=0 取 bit15，col=15 取 bit0。

用法
---------------------------------------------------------------------------
    python tools/gen_font_mif.py
    会在两处各写一份（TD 对 INIT_FILE 的相对路径基准不确定，logo.mif 就是这么做的）：
        user_source/hdl_source/mif/font16.mif
        td_project/mif/font16.mif
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
HDL = os.path.dirname(HERE)                      # .../user_source/hdl_source
PROJ = os.path.dirname(os.path.dirname(HDL))     # .../lab_ex3_osd

SRC = os.path.join(HDL, "osd_char_lib.v")

# char_idx 顺序（必须和 target_osd.v 里的 localparam 一致）
ORDER = [chr(ord('A') + i) for i in range(26)] + [str(i) for i in range(10)]
EXTRA = {" ": 36, ":": 37}

# ★ 2026-10-29：姿态文字要显示中文（站 / 坐 / 蹲），16x16 点阵
#   2026-10-29 改：新增 改锥/魔方/黑色物体 用中文（41~48）
#   用 Windows 自带字体渲染（微软雅黑 15px，阈值 110），再并进同一份字库。
#   索引必须和 target_osd.v 的 localparam 一致。
ZH_CHARS = [
    ("站", 38), ("坐", 39), ("蹲", 40),
    ("改", 41), ("锥", 42), ("魔", 43), ("方", 44),
    ("黑", 45), ("色", 46), ("物", 47), ("体", 48),
    # ★ 2026-10-30：黑色物体标签改「小船」，魔方换成「蓝色物体」
    ("小", 49), ("船", 50), ("蓝", 51),
    # ★ 2026-10-30：新增「黄色」类（黄色改锥手柄）
    ("黄", 52),
    # ★ 2026-10-30：新增「红色」类（红色 3D 打印件）
    ("红", 53),
]
ZH_FONT = r"C:/Windows/Fonts/msyh.ttc"


def render_zh(ch, size=15, thresh=110, dy=-2):
    """把汉字渲染成 16x16 点阵（返回 16 个 16 位整数，bit15 = 最左）"""
    from PIL import Image, ImageDraw, ImageFont
    f = ImageFont.truetype(ZH_FONT, size)
    im = Image.new("L", (16, 16), 0)
    ImageDraw.Draw(im).text((0, dy), ch, fill=255, font=f)
    px = im.load()
    rows = []
    for r in range(16):
        v = 0
        for c in range(16):
            if px[c, r] > thresh:
                v |= (1 << (15 - c))
        rows.append(v)
    return rows

# osd_char_lib 里的 localparam 名字
NAME = {"COLON": ":"}


def parse_glyphs(path):
    """返回 {字符: [16 个 16 位整数]}"""
    glyphs = {}
    cur = None
    rows = {}
    pat_char = re.compile(r"^\s*CHAR_([A-Z0-9_]+)\s*:\s*begin")
    pat_row = re.compile(r"4'd(\d+)\s*:\s*O_row_bits\s*=\s*16'h([0-9a-fA-F]+)\s*;")
    with open(path, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            m = pat_char.match(line)
            if m:
                cur = m.group(1)
                rows = {}
                glyphs[cur] = rows
                continue
            if cur is None:
                continue
            m = pat_row.search(line)
            if m:
                r = int(m.group(1))
                if 0 <= r <= 15:
                    rows[r] = int(m.group(2), 16)
    return glyphs


def key_of(name):
    """CHAR_A -> 'A' ; CHAR_0 -> '0' ; CHAR_COLON -> ':'"""
    if name in NAME:
        return NAME[name]
    if len(name) == 1:
        return name
    return None


def main():
    glyphs = parse_glyphs(SRC)
    table = {}
    for name, rows in glyphs.items():
        k = key_of(name)
        if k is None:
            continue
        table[k] = [rows.get(i, 0) for i in range(16)]

    missing = [c for c in ORDER if c not in table]
    if missing:
        raise SystemExit("字库里缺字符: %s" % missing)

    # 汉字点阵（PIL 不可用时跳过，已有 mif 里的汉字保持不变 —— 但那样就不会更新）
    zh = None
    try:
        zh = {}
        for ch, i in ZH_CHARS:
            zh[i] = render_zh(ch)
        print("已渲染汉字: %s" % ", ".join(c for c, _ in ZH_CHARS))
    except Exception as e:
        print("⚠ 汉字渲染失败(%s)，字库里的 38~40 会保持空白" % e)

    lines = []
    # MIF 必须是纯 ASCII：TD 读 INIT_FILE 时不做编码转换，中文注释会报错
    lines.append("-- font16.mif : 16x16 ASCII font for target_osd.v (generated by tools/gen_font_mif.py, do not edit)")
    lines.append("DEPTH = 1024;")
    lines.append("WIDTH = 16;")
    lines.append("ADDRESS_RADIX = HEX;")
    lines.append("DATA_RADIX = HEX;")
    lines.append("CONTENT")
    lines.append("BEGIN")

    for addr in range(1024):
        idx = addr >> 4
        row = addr & 0xF
        val = 0
        if idx < 36:
            ch = ORDER[idx]
            val = table[ch][row]
        elif idx == 36:
            val = 0            # 空格
        elif idx == 37:
            val = table[":"][row]
        elif zh is not None and idx in zh:
            val = zh[idx][row]
        lines.append("%03X : %04X;" % (addr, val))

    lines.append("END;")
    txt = "\n".join(lines) + "\n"

    outs = [
        os.path.join(HDL, "mif", "font16.mif"),
        os.path.join(PROJ, "td_project", "mif", "font16.mif"),
    ]
    for p in outs:
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="ascii", newline="\n") as f:
            f.write(txt)
        print("write %s" % p)

    # 自检：把 'R' 打出来看看（肉眼确认位序没错）
    if zh:
        for ch, i in ZH_CHARS:
            print("\n自检 '%s':" % ch)
            for row in range(16):
                v = zh[i][row]
                print("  %2d |%s|" % (row, "".join("#" if (v >> (15 - c)) & 1 else "." for c in range(16))))

    print("\n自检 'R'（# = 亮）:")
    for row in range(16):
        v = table["R"][row]
        s = "".join("#" if (v >> (15 - c)) & 1 else "." for c in range(16))
        print("  %2d |%s|" % (row, s))


if __name__ == "__main__":
    main()

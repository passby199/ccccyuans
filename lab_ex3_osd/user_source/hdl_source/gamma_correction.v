//=============================================================================
//  gamma_correction.v  --  Gamma 0.45 显示端编码（解决"画面偏暗/不通透"）
//
//  串在 enhance 与 hdmi_mixer 之间，纯组合逻辑 + 1 级寄存，0 块 ERAM。
//
//  为什么需要
//  ---------------------------------------------------------------------------
//  传感器输出是线性的，而 HDMI 显示器本身带 gamma≈2.2。线性值直接送屏，
//  中间调会明显偏暗（线性 128 显示出来只有 0.5^2.2 ≈ 22% 亮度）。
//  这里做 gamma=0.45 编码 out = 255*(in/255)^0.45，把整条曲线抬起来，
//  正好补偿显示器的非线性。这是整条链路里对"偏暗/不通透"收益最大的一级。
//
//  v2 改进：4 段 -> 8 段折线（暗部提亮）
//  ---------------------------------------------------------------------------
//  v1 用 4 段折线（断点 0/64/128/192/255）。实测其深暗部（in 0~31）平均仅
//  输出 32.7，而理想 gamma 0.45 应为 67.3 —— 暗部只有应有亮度的一半，这就是
//  "画面发闷、不通透"的量化根因。v1 全曲线平均误差 7.60 LSB。
//
//  v2 改用 8 段折线（断点 0/16/32/48/64/96/128/192/255），断点输出直接取
//  round(255*(x/255)^0.45)：0/73/100/120/137/164/187/224/255，并在每段
//  补上四舍五入（+半 LSB 再右移），消除截断带来的系统性偏暗。效果：
//      平均误差      7.60 -> 1.50 LSB（降 80%）
//      深暗部 (0-31) 32.7 -> 60.0  (+27.3)   <- 通透度的主要来源
//      暗部  (32-63) 101.2 -> 118.8 (+17.6)
//      中调  (64-127)161.1 -> 162.6 (+1.5)   <- 几乎不动
//      亮部 (128-255)222.1 -> 222.4 (+0.2)   <- 高光不冲爆
//  白场仍为 255、黑场为 0、全曲线严格单调，无副作用。
//
//  BLACK_LEVEL：黑电平扣除（8bit 域），默认 8'd0 即不改变现有行为。
//  仅当你实测确认"黑场发灰、黑不够黑"时才调大。注意：黑电平扣除必须配合
//  满量程归一化 x'=(x-BL)*255/(255-BL)，否则白场会变灰 —— 本模块的
//  折线断点已按 BL=0 标定，若要启用黑电平请先把断点表整体右移 BL。
//  SC500CS RAW10 黑电平典型值 64，经 demosaic 的 >>2 后约为 16，可作起点。
//=============================================================================

module gamma_correction #(
    parameter [7:0] BLACK_LEVEL = 8'd0,
    //-------------------------------------------------------------------------
    // 色度保持模式（CHROMA_KEEP）
    //
    //   0 = 逐通道独立查表（原始行为）
    //       out_R = gamma(R), out_G = gamma(G), out_B = gamma(B)
    //       问题：gamma 在低输入斜率 4.56、高输入斜率 0.49，
    //             会把通道间**色差非线性压扁**（肤色彩度实测掉 46%）。
    //             画面表现为「发灰、褪色」。
    //
    //   1 = gamma 只作用于亮度，色差完整保留（推荐）
    //       Y_in   = (R + G + B) / 3          <- 等权，无色偏
    //       Y_out  = gamma(Y_in)
    //       out_x  = Y_out + (x - Y_in)       <- 加回原始色差
    //       这样 gamma 的提亮效果完整保留，而颜色浓度不受损失。
    //
    //   ★ 为什么必须用等权 (R+G+B)/3：
    //     若用 (R+2G+B)/4，G 权重是 R/B 的两倍，加回色差时
    //     三个通道的修正量不等，会系统性偏移色相（往粉/品红跑）。
    //-------------------------------------------------------------------------
    parameter integer CHROMA_KEEP = 1,
    //-------------------------------------------------------------------------
    // ★ 饱和度增强（SAT_BOOST_Q4）—— 2026-09-19 新增
    //
    //   在 CHROMA_KEEP 之后、输出之前，按比例放大色差：
    //       Y   = (R + G + B) / 3      等权亮度
    //       out = Y + K * (in - Y)     色差放大 K 倍，亮度不变
    //
    //   参数是 Q4 定点（16 = 1.0）：
    //       16 = 1.00  直通（关闭）★ 验证对齐的基准值
    //       24 = 1.50  温和
    //       32 = 2.00  明显
    //       48 = 3.00  ★ 推荐起点
    //       64 = 4.00  ★★ 「鲜艳卡通」档
    //       96 = 6.00  很浓（配合自适应限幅可达 S≈0.7）
    //
    //   ★★ 千万别改成「三通道不同系数」或用 (R+2G+B)/4 当亮度 ——
    //      那会让色相漂移，画面推向粉/品红（PRE_SAT_K 踩过的坑）。
    //      本实现严格保证：out_r - out_g = k*(in_r - in_g)，
    //      色差按比例放大，色相【严格不变】。
    //
    //   ★ 高饱和保护（2026-09-19 第四轮改为「自适应软限幅」）：
    //     不再是"越界就整像素退回原值"（那会造成倒 U 形 + 画面割裂），
    //     而是【每个像素自动求不越界的最大 k】再与目标值取 min。
    //     于是永不越界、K 越大 S 越高（单调）、高光区平滑收缩。
    //     详见下方 SAT_BOOST 实现段的第四轮说明。
    //-------------------------------------------------------------------------
    parameter [7:0] SAT_BOOST_Q4 = 8'd48
)(
    input  wire        I_clk,
    input  wire        I_rst_n,
    input  wire        I_de,
    input  wire [23:0] I_data,      // {R[23:16], G[15:8], B[7:0]}
    output reg         O_de,
    output reg  [23:0] O_data
);

    //-------------------------------------------------------------------------
    // 8 段线性近似 gamma 0.45（断点输出 = round(255*(in/255)^0.45)）
    //
    //   段   in 区间    断点out      斜率实现 (带四舍五入)
    //   0    0 ~  15    0  ->  73    out = (xb*146+16)>>5
    //   1   16 ~  31   73  -> 100    out = 73  + ((xb-16)*54+16)>>5
    //   2   32 ~  47  100  -> 120    out = 100 + ((xb-32)*40+16)>>5
    //   3   48 ~  63  120  -> 137    out = 120 + ((xb-48)*34+16)>>5
    //   4   64 ~  95  137  -> 164    out = 137 + ((xb-64)*27+16)>>5
    //   5   96 ~ 127  164  -> 187    out = 164 + ((xb-96)*23+16)>>5
    //   6  128 ~ 191  187  -> 224    out = 187 + ((xb-128)*37+32)>>6
    //   7  192 ~ 255  224  -> 255    out = 224 + ((xb-192)*126+128)>>8
    //
    //  斜率都是小常数，综合成移位加法，几乎不占资源。
    //-------------------------------------------------------------------------
    function [7:0] F_gamma;
        input [7:0] x;
        reg  [9:0] xb;
        begin
            xb = (x > BLACK_LEVEL) ? (x - BLACK_LEVEL) : 10'd0;

            if      (xb < 10'd16)  F_gamma = (xb * 16'd146 + 16'd16) >> 5;
            else if (xb < 10'd32)  F_gamma = 8'd73  + (((xb - 10'd16)  * 16'd54  + 16'd16) >> 5);
            else if (xb < 10'd48)  F_gamma = 8'd100 + (((xb - 10'd32)  * 16'd40  + 16'd16) >> 5);
            else if (xb < 10'd64)  F_gamma = 8'd120 + (((xb - 10'd48)  * 16'd34  + 16'd16) >> 5);
            else if (xb < 10'd96)  F_gamma = 8'd137 + (((xb - 10'd64)  * 16'd27  + 16'd16) >> 5);
            else if (xb < 10'd128) F_gamma = 8'd164 + (((xb - 10'd96)  * 16'd23  + 16'd16) >> 5);
            else if (xb < 10'd192) F_gamma = 8'd187 + (((xb - 10'd128) * 16'd37  + 16'd32) >> 6);
            else                   F_gamma = 8'd224 + (((xb - 10'd192) * 16'd126 + 16'd128) >> 8);
        end
    endfunction

    //-------------------------------------------------------------------------
    // 通道值
    //-------------------------------------------------------------------------
    wire [7:0] i_r = I_data[23:16];
    wire [7:0] i_g = I_data[15: 8];
    wire [7:0] i_b = I_data[ 7: 0];

    //-------------------------------------------------------------------------
    // 模式 0：逐通道独立查表（原行为）
    //-------------------------------------------------------------------------
    wire [7:0] gr = F_gamma(i_r);
    wire [7:0] gg = F_gamma(i_g);
    wire [7:0] gb = F_gamma(i_b);

    //-------------------------------------------------------------------------
    // 模式 1：色度保持 —— gamma 只作用于等权亮度，色差原样保留
    //
    //   Y_in  = (R + G + B) / 3                    等权亮度（无色偏）
    //   Y_out = F_gamma(Y_in)                       gamma 提亮
    //   d     = Y_out - Y_in                        亮度修正量（有符号）
    //   out_x = clamp(x + d)                        三通道加同一个 d，色差不变
    //
    //   注意 d 对三通道**完全相同**，所以 (R'-G') = (R-G) 严格成立，
    //   色相和彩度都不受 gamma 影响 —— 这是修「褪色」的关键。
    //
    //   ★ d 必须限幅（关键细节）：
    //     若直接把 d 加到三通道，纯红 (255,0,0) 的 Y_in=85、Y_out=150，
    //     d=+65 会让 R 撞顶、G/B 被抬到 65 => 变成粉色 (255,65,65)，
    //     高饱和色反而褪色。
    //     解决：正向 d 限制为 d <= 255 - max(R,G,B)，
    //           这样三通道一起加时都不会溢出，0 通道也不会被抬起来。
    //     实测彩度保留率由 95.9% 提升到 100.0%（纯红仍为 255 彩度）。
    //-------------------------------------------------------------------------
    wire [9:0] y3_sum = {2'b00, i_r} + {2'b00, i_g} + {2'b00, i_b};
    wire [7:0] y3_in  = (y3_sum + 10'd1) / 10'd3;      // 四舍五入除 3
    wire [7:0] y3_out = F_gamma(y3_in);

    //-------------------------------------------------------------------------
    // ★ 2026-10-28 修时序：这里插一级流水（原 Slack −3.267ns，u_gamma/add43）
    //   原链：I_data → y3_sum(2加法) → +1 → /3(乘法) → F_gamma(8段折线)
    //        → d_raw(减法) → 限幅 → ck_r(加法) → 钳位 → O_data
    //   在 y3_in/y3_out 之后打拍，把链切成两段；i_r/g/b 同步延迟保持像素对齐。
    //   代价：gamma 整体多 1 拍延迟，O_de 跟着延一拍（下游 enhance 自动跟上）。
    //-------------------------------------------------------------------------
    reg [7:0] y3_in_r, y3_out_r;
    reg [7:0] i_r_r, i_g_r, i_b_r;
    reg       de_mid;

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            y3_in_r  <= 8'd0;
            y3_out_r <= 8'd0;
            i_r_r    <= 8'd0;
            i_g_r    <= 8'd0;
            i_b_r    <= 8'd0;
            de_mid   <= 1'b0;
        end
        else begin
            y3_in_r  <= y3_in;
            y3_out_r <= y3_out;
            i_r_r    <= i_r;
            i_g_r    <= i_g;
            i_b_r    <= i_b;
            de_mid   <= I_de;
        end
    end


    // 有符号差值 d = y3_out - y3_in，范围 -255..255，用 9bit
    wire signed [8:0] d_raw = {1'b0, y3_out_r} - {1'b0, y3_in_r};
    wire signed [9:0] d_f   = d_raw;                   // 符号扩展

    // 三通道最大值 / 最小值
    wire [7:0] rgb_max = (i_r_r > i_g_r) ? ((i_r_r > i_b_r) ? i_r_r : i_b_r)
                                         : ((i_g_r > i_b_r) ? i_g_r : i_b_r);
    wire [7:0] rgb_min = (i_r_r < i_g_r) ? ((i_r_r < i_b_r) ? i_r_r : i_b_r)
                                         : ((i_g_r < i_b_r) ? i_g_r : i_b_r);

    // 正向余量 / 负向余量
    //   ★ 必须显式声明为 signed：Verilog 中 signed 与 unsigned 混用比较时，
    //     整个表达式会被当成 unsigned，负数会被错误地解释成大正数。
    //     d_f 是 signed，若 room_up 是 unsigned，(d_f > room_up) 判断就失效了。
    wire signed [9:0] room_up = {2'b00, 8'd255} - {2'b00, rgb_max}; // 0..255
    wire signed [9:0] room_dn = {2'b00, rgb_min};                   // 0..255

    // 限幅后的 d（全部在 signed 域内运算）
    //   正向 d_f > 0 : 取 min(d_f, room_up)     -> 不能加到溢出 255
    //   负向 d_f < 0 : 取 max(d_f, -room_dn)    -> 不能减到小于 0
    //   其余         : 直通
    wire signed [9:0] d_up  = (d_f > room_up)  ? room_up  : d_f;
    wire signed [9:0] d_dn  = (d_f < -room_dn) ? -room_dn : d_f;
    wire signed [9:0] d_lim = (d_f > 10'sd0) ? d_up :
                              (d_f < 10'sd0) ? d_dn : 10'sd0;

    wire signed [9:0] ck_r = {2'b00, i_r_r} + d_lim;
    wire signed [9:0] ck_g = {2'b00, i_g_r} + d_lim;
    wire signed [9:0] ck_b = {2'b00, i_b_r} + d_lim;

    // 保险起见再夹一次（限幅后理论上不会越界）
    wire [9:0] ck_rp = ck_r[9] ? 10'd0 : ck_r;
    wire [9:0] ck_gp = ck_g[9] ? 10'd0 : ck_g;
    wire [9:0] ck_bp = ck_b[9] ? 10'd0 : ck_b;

    wire [7:0] kr = (ck_rp > 10'd255) ? 8'd255 : ck_rp[7:0];
    wire [7:0] kg = (ck_gp > 10'd255) ? 8'd255 : ck_gp[7:0];
    wire [7:0] kb = (ck_bp > 10'd255) ? 8'd255 : ck_bp[7:0];

    //-------------------------------------------------------------------------
    // 输出选择
    //-------------------------------------------------------------------------
    wire [7:0] cr = (CHROMA_KEEP != 0) ? kr : gr;
    wire [7:0] cg = (CHROMA_KEEP != 0) ? kg : gg;
    wire [7:0] cb = (CHROMA_KEEP != 0) ? kb : gb;

    //=========================================================================
    // ★★★ SAT_BOOST —— 饱和度增强（2026-09-19 新增）★★★
    //
    //   【为什么需要它 —— 根因分析】
    //     用户反复反馈「没有颜色」「只有灰色」「凑近看感觉就是灰的」。
    //     全链路排查后的实测数据（屏摄照片反推，已做反 gamma）：
    //         AWB 输出均值  R=68.0  G=78.3  B=90.7
    //         彩度（max-min）均值仅 24.5、中位 23
    //     而高饱和的 logo 红/蓝显示正常 → 说明【不是颜色丢失，是饱和度不足】。
    //
    //     AWB、gamma、cartoonize 三级都已经证明【不损失彩度】：
    //       - gamma CHROMA_KEEP：三通道加同一个 d → 色差严格不变（100%）
    //       - cartoonize：量化只作用于亮度，三通道加同一 delta（85~100%）
    //       - AWB：只做全局通道增益，是色温校正不是饱和度处理
    //     所以画面「灰」的根源是【场景本身以低饱和的灰白墙面为主】
    //     + 【SC500 这类小靶面 sensor 的 RAW 彩度本来就偏低】。
    //
    //   【算法】在亮度不变的约束下放大色差：
    //       Y   = (R + G + B) / 3          等权亮度（无色偏）
    //       out = Y + K * (in - Y)         色差放大 K 倍
    //
    //     展开：out_r = Y + K*(cr - Y)
    //   用定点实现避免乘法器过多：
    //       out_r = (cr*(K_Q4) + Y*(16 - K_Q4)) >> 4
    //     其中 K_Q4 是 Q4 定点（16 = 1.0, 24 = 1.5, 32 = 2.0）
    //
    //   ★★ 三个必须遵守的约束（否则会重蹈 PRE_SAT_K 的坑）：
    //     1. 【必须用等权 Y = (R+G+B)/3】
    //        曾经用 (R+2G+B)/4，G 权重翻倍 → K>1 时 R 单方面撞 255、
    //        G/B 被压低 → 画面推向粉/品红。等权 Y 才不会偏色。
    //     2. 【必须对三通道用同一个 K 和同一个 Y】
    //        这样色差按比例放大，色相严格不变：
    //          out_r - out_g = K*(cr - cg)
    //        R/G/B 大小关系不变 → 色相不变 ✓
    //     3. 【必须限幅】防止高饱和像素撞顶后色相漂移
    //        撞顶后 (255,70,70) 会变粉。限幅策略：
    //          先算出放大后的值，再单独夹到 [0,255]，
    //          同时用一个「统一缩放」策略保持色差比例：
    //          若放大后超出范围，则退回到原始值（不做增益）
    //          —— 简单、安全，且只影响极少数高饱和像素。
    //
    //   ★ 参数 SAT_BOOST_Q4：
    //        16 = 1.00  关闭（输出 == 输入，直通基准）
    //        24 = 1.50  温和
    //        32 = 2.00  明显
    //        48 = 3.00  ★ 推荐起点（彩色物体已达标）
    //        64 = 4.00  ★★ 强烈（「鲜艳卡通」档，自适应限幅下仍安全）
    //        96 = 6.00  很浓（配合自适应限幅可达 S≈0.7）
    //      ★ 现在可以放心用大值 —— 见下方「第四轮：自适应软限幅」。
    //
    //   ★ 验证方法（直通基准）：
    //        SAT_BOOST_Q4 = 16 时，输出必须与输入【逐位相同】（只差固定延迟）。
    //        这是确认对齐正确、无副作用的第一手段。
    //
    //   ★ 时序影响：纯组合逻辑插在【原有寄存器之前】，
    //     不增加流水线级数 → de/data 对齐完全不受影响。
    //
    //   ★★ 2026-09-19 第三轮认知修正（色相优先，仍然成立）★★
    //     曾把 SAT_BOOST_Q4 从 24 加大到 40/57 试图解决"颜色淡"，被否证：
    //       照片彩度 top 0.1% = 89.7   ← 通路完全能出鲜艳色
    //       90% 的彩色像素都是青/蓝系 → 真问题是【整画面被染上青蓝】
    //     **饱和度高 ≠ 颜色对。先修色相（AWB），再谈饱和度。**
    //     → 该结论已由 AWB_STRENGTH_Q8=256（v7）修复，色相已准。
    //
    //   ★★ 第四轮修订（2026-09-19 最终版）：硬退回 → 自适应软限幅 ★★
    //
    //   【旧实现的缺陷 —— 实测发现】
    //     旧策略是「任一通道越界 → 整像素退回原值」。行为上很安全，
    //     但导致 S 对 K 呈【倒 U 形】，K 加到一定程度反而变差：
    //
    //       K_Q4     退回原值比例    有色像素 S 中位
    //        48         5.3%            0.455
    //        64        13.1%            0.511
    //        80        22.2%            0.530   ← 峰值
    //        96        31.8%            0.520   ← 开始回落
    //       128        49.0%            0.378   ← 明显劣化
    //
    //     → 因为 K 越大，越多的像素被【整块退回】，退回的像素完全不增强，
    //       把统计拉回去了。而且「增强/退回」在相邻像素间跳变 → 画面割裂。
    //
    //   【新实现 —— 自适应降 K】
    //     对每个像素求「三通道都不越界的最大 K」，再取 min(目标K, 允许K)：
    //         向上： Y*16 + (v-Y)*k <= 255*16  →  k <= (255*16 - Y*16)/(v-Y)
    //         向下： Y*16 + (v-Y)*k >= 0       →  k <= (Y*16)/(Y-v)
    //     k 取上述两个上界的最小值。则【永不越界】，无需退回。
    //
    //     效果（同一色彩样本，20k 组）：
    //       K_Q4        硬退回 S中位      自适应 S中位
    //        48           0.455            0.463
    //        64           0.511            0.564
    //        80           0.530            0.644
    //        96           0.520            0.710
    //       128           0.378            0.804   ← 单调上升，无倒 U
    //
    //     ★ 为什么色相仍然严格不变：
    //       三通道共用【同一个自适应 k】与【同一个 Y】，
    //       故 out_r - out_g = k*(cr - cg) 仍按比例缩放。
    //       实测（K=24/32/48/64/96）：通道排序改变 0 次，偏差 ≤0.94 LSB ✓
    //
    //     ★ 灰度安全性：纯灰/纯黑/纯白像素 (v == Y) 时 k 不受约束
    //       （不参与求上界），且 d = 0 → 输出 == 输入，逐位不变。
    //       实测 (0,0,0)/(255,255,255)/(128,128,128)/(250,250,250) 全部不变 ✓
    //
    //     ★ 高光行为：亮且高饱和的像素（如 R≈255）自动收缩 k，
    //       输出恰好贴到 255 而不溢出 → 既保留全部色相，又不会突然变淡。
    //
    //     ★ 时序：仍然是纯组合逻辑，不增加流水线级数；
    //       ★ 且【没有引入任何除法器】 —— 求 k 上界用的除法全部由
    //         「逐位试减」（移位+比较）实现，纯 LUT。
    //         （反面教训：用 `/` 会综合出 3 个真除法器，约 1900 LUT，
    //           对 720P 无关痛痒但白白浪费，且深度大。见下 k_limit。）
    //=========================================================================
    wire [9:0] s_sum = {2'b00, cr} + {2'b00, cg} + {2'b00, cb};
    wire [7:0] s_y   = (s_sum + 10'd1) / 10'd3;         // 等权亮度，四舍五入

    // 有符号色差 (in - Y)，范围 -255..255
    wire signed [9:0] s_dr = $signed({2'b00, cr}) - $signed({2'b00, s_y});
    wire signed [9:0] s_dg = $signed({2'b00, cg}) - $signed({2'b00, s_y});
    wire signed [9:0] s_db = $signed({2'b00, cb}) - $signed({2'b00, s_y});

    //-------------------------------------------------------------------------
    // ★ 自适应 K 上界计算（Q4 定点）
    //
    //   【数学推导 —— 一次说清，别再搞混 dv 与 dv*16】
    //
    //     目标：out = Y + (k/16)*(v - Y)        k 为 Q4 定点，k=16 即 1.0x
    //     记   dv = v - Y   （原始色差，范围 -255..255，【不缩放】）
    //          yq = Y*16    （亮度缩放 16 倍）
    //
    //     两边乘 16 消掉小数：
    //          out*16 = yq + k*dv
    //     即    out = (yq + k*dv) >> 4
    //
    //     ★ 关键：dv 不乘 16，k 也不除 16 —— 16 的缩放全部由 yq 与最后的 >>4 承担。
    //        （上一版把 dv 也乘了 16，等于多乘一次，导致 k=16 时输出
    //          (yq + 16*dv)>>4 ≠ v，直通基准直接失败。）
    //
    //     不越界约束（0 <= out*16 <= 255*16 = 4080）：
    //          yq + k*dv <= 4080   →  k <= (4080 - yq) / dv      (dv > 0)
    //          yq + k*dv >= 0      →  k <= (   yq   ) / (-dv)    (dv < 0)
    //
    //     所以 k_limit 里做除法用的是【原始 dv】，room 用 yq 域（0..4080）。
    //-------------------------------------------------------------------------
    wire [12:0] s_yq = {5'b0, s_y} * 13'd16;            // yq = Y*16，最大 4080 ✓

    //-------------------------------------------------------------------------
    // 单通道「允许 K 上界」—— 组合函数，无寄存器、无除法器
    //   输入 dv = v - Y（signed 9bit，范围 -255..255）
    //   求满足  yq + k*dv ∈ [0, 4080]  的最大 k（0..255）
    //   ★ 用「逐位试减」实现除法：从 bit7 试到 bit0，纯 LUT，
    //     面积远小于真除法器（divider ≈ 640 LUT，3 个就 2000 LUT）。
    //-------------------------------------------------------------------------
    function [7:0] k_limit;
        input signed [8:0] dv;
        reg   [12:0] room;      // 该方向可用余量（yq 域），0..4080
        reg   [8:0]  absd;      // |dv|，0..255
        reg   [7:0]  kk;
        reg   [16:0] acc;       // ★ 17bit：255 << 8 = 65280 < 2^17 ✓
        reg   [16:0] trial;
        integer      i;
        begin
            if (dv > 9'sd0) begin
                room = 13'd4080 - s_yq;             // 向上余量（yq <= 4080，不会回绕）
                absd = dv;
            end
            else if (dv < 9'sd0) begin
                room = s_yq;                        // 向下余量
                absd = -dv;                         // signed 取负，9bit 足够
            end
            else begin
                room = 13'd4080;
                absd = 9'd0;                        // 纯灰像素：dv=0，不构成约束
            end
            // 逐位试减：求满足 absd*k <= room 的最大 k（bit7..bit0）
            kk  = 8'd0;
            acc = 17'd0;
            for (i = 7; i >= 0; i = i - 1) begin
                trial = acc + (absd << i);          // ★ 9bit << 7 => 16bit，17bit 目标不截断
                if (trial <= {4'b0, room}) begin    // ★ 两侧都补到 17bit 再比
                    acc = trial;
                    kk  = kk | (8'd1 << i);
                end
            end
            k_limit = kk;
        end
    endfunction

    wire [7:0] s_kr = k_limit(s_dr);
    wire [7:0] s_kg = k_limit(s_dg);
    wire [7:0] s_kb = k_limit(s_db);

    // 三通道取 min，再与目标 SAT_BOOST_Q4 取 min
    wire [7:0] s_kmin_raw = (s_kr < s_kg) ? ((s_kr < s_kb) ? s_kr : s_kb)
                                          : ((s_kg < s_kb) ? s_kg : s_kb);
    wire [7:0] s_k_sel = (s_kmin_raw < SAT_BOOST_Q4) ? s_kmin_raw : SAT_BOOST_Q4;

    //-------------------------------------------------------------------------
    // 下限保护：k 至少为 16（=1.0x）
    //   ★ 为什么 k<16 时直接取 16 是安全的：
    //     自适应上界 k_allowed < 16 意味着该像素【很亮且很饱和】
    //     （room 很小而 |dv| 很大）。此时 k=16 给出
    //         out = (yq + 16*dv)>>4 = ((Y+dv)*16)>>4 = v = 原值
    //     即【直通】，恒在 0..255 内，绝不会越界。✓
    //-------------------------------------------------------------------------
    wire [7:0] s_k = (s_k_sel < 8'd16) ? 8'd16 : s_k_sel;

    //-------------------------------------------------------------------------
    // 用选定的 k 做放大：out = (yq + k*dv) >> 4
    //   k  ∈ [16, 255]（8bit）
    //   dv ∈ [-255, 255]（9bit signed）
    //   ★ 乘积范围 ±255*255 ≈ ±65025 → 17bit signed 足够；
    //     这里给 18bit，留 1bit 余量，避免任何隐式截断。
    //-------------------------------------------------------------------------
    wire signed [17:0] s_mr = $signed({{9{s_dr[8]}}, s_dr}) * $signed({1'b0, s_k});
    wire signed [17:0] s_mg = $signed({{9{s_dg[8]}}, s_dg}) * $signed({1'b0, s_k});
    wire signed [17:0] s_mb = $signed({{9{s_db[8]}}, s_db}) * $signed({1'b0, s_k});

    // 结果 = yq + k*dv ，因 k 不越界，必落在 0..4080
    wire signed [17:0] s_tr = $signed({5'b0, s_yq}) + s_mr;
    wire signed [17:0] s_tg = $signed({5'b0, s_yq}) + s_mg;
    wire signed [17:0] s_tb = $signed({5'b0, s_yq}) + s_mb;

    // >>4（算术右移，保留符号；因 k 不越界，结果必在 0..4080）
    wire [9:0] s_fr = s_tr[13:4];
    wire [9:0] s_fg = s_tg[13:4];
    wire [9:0] s_fb = s_tb[13:4];

    // 夹到 0..255（保险；正常情况下 s_k 的自适应上界已保证不溢出）
    wire [7:0] sr = (s_fr > 10'd255) ? 8'd255 : s_fr[7:0];
    wire [7:0] sg = (s_fg > 10'd255) ? 8'd255 : s_fg[7:0];
    wire [7:0] sb = (s_fb > 10'd255) ? 8'd255 : s_fb[7:0];

    //-------------------------------------------------------------------------
    // 最终输出
    //-------------------------------------------------------------------------
    wire [7:0] o_r = sr;
    wire [7:0] o_g = sg;
    wire [7:0] o_b = sb;

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            O_de   <= 1'b0;
            O_data <= 24'd0;
        end
        else begin
            O_de   <= de_mid;          // ★ 多 1 拍，与流水级对齐
            O_data <= {o_r, o_g, o_b};
        end
    end

endmodule

//=============================================================================
//  param_ctrl.v  --  串口在线调参（省掉每次改参数都要重新编译）
//
//  为什么要有这个
//  ---------------------------------------------------------------------------
//  原来 DIFF_TH / MIN_AMP / HOLD / REFRACTORY / RHYTHM_TOL / GRAY_LO / GRAY_HI
//  全是 Verilog 里的 parameter，改一个值就要重编译一次（实测一次 75~92 分钟，
//  因为本工程 slice 用到 84%、且时序不收敛，布线器要反复迭代）。
//  做成运行时寄存器之后：**采集 → 分析 → 直接发一条串口命令 → 立刻生效**。
//
//  命令格式（ASCII，以 \n 或 \r 结束）
//  ---------------------------------------------------------------------------
//      P<序号>=<十进制值>        例：P4=3000
//      R                        清零跳绳计数（等价拨码开关 SW1）
//
//  序号表
//  ---------------------------------------------------------------------------
//      0  DIFF_TH      前景判决阈值（检测灵敏度），0~255
//      1  GRAY_LO      亮度门下限
//      2  GRAY_HI      亮度门上限
//      3  PROJ_TH      包围框投影裁剪阈值（一行/一列最少几个前景格子）
//      4  MIN_AMP      幅度门（Σy 峰峰值要超过它才算在动）
//      5  HOLD         包络峰值保持期（帧）
//      6  REFRACTORY   不应期（帧）
//      7  RHYTHM_TOL   节律容差（帧）
//
//  ⚠ 2026-10-18：P4~P8 现在写的是【当前运动模式】的槽位，不是全局值。
//     三个模式（跳绳/深蹲/开合跳）各有一套手调参数，按 KEY1/KEY2 切换时
//     手调值跟着模式走，互不覆盖。某个模式从没调过就继续用运动模式表的值。
//     P8（判据来源）也分模式 —— 虽然目前三个模式都是 y0。
//
//  为什么不直接在 RTL 里认 "MIN_AMP" 这种名字
//     字符串比较要几十个 LUT 的比较器。PC 端脚本（tools/serial_param.py）
//     负责把名字翻译成序号，所以人用的时候还是写名字。
//
//  ⚠️ 上电默认值 = 改之前 RTL 里的 parameter 原值，保证**不加命令时行为完全不变**。
//     特别是 HOLD 仍是 25 —— 但注意本板是 720p60（60fps），
//     参数当年是按 30fps 定的，60fps 下时间常数只有一半。
//     建议用串口把 HOLD 调到 50、REFRACTORY 调到 14 试试（慢速运动会更准）。
//
//  资源：约 150~200 LUT，0 DSP（乘 10 用移位加法）
//=============================================================================

module param_ctrl #(
    // 上电默认值：与 design_top_wrapper / motion_stats / jump_counter 的
    // parameter 原值严格一致
    parameter [7:0]  DEF_DIFF_TH    = 8'd10,
    parameter [7:0]  DEF_GRAY_LO    = 8'd16,
    parameter [7:0]  DEF_GRAY_HI    = 8'd235,
    parameter [7:0]  DEF_PROJ_TH    = 8'd2,
    parameter [24:0] DEF_MIN_AMP    = 25'd2500,
    parameter [7:0]  DEF_HOLD       = 8'd25,
    parameter [7:0]  DEF_REFRACTORY = 8'd7,
    parameter [7:0]  DEF_RHYTHM_TOL = 8'd2,
    // 判据来源默认值：0 = Σy（与改动前一致），1 = 头顶 y0
    //   上电保持 0，保证不加命令时行为完全不变；
    //   想用头顶判据就发 P8=1（或改成 1 让它上电默认就用头顶）
    parameter        DEF_USE_Y0     = 1'b0
)(
    input  wire        I_clk,
    input  wire        I_rst_n,
    // 串口
    //  ★★★ 2026-10-28 修复致命 bug：这里原来漏了位宽，默认只有 1 位！★★★
    //    原写法 `input wire I_rx_data` → 1 位；顶层接 8 位的 S_rx_byte 时
    //    Verilog 静默截断只留 bit0，导致 is_digit / is_p / is_eq / is_nl 全部恒假，
    //    解析器永远进不了任何状态 → 所有 P 参数都改不动（但 LED 靠 rx_valid 照常亮）。
    input  wire [7:0]  I_rx_data,        // 收到的字节（必须是 8 位！）
    input  wire        I_rx_valid,       // 1 拍脉冲
    //------------------------------------------------------------------
    // 2026-10-18 新增：手调参数【按运动模式分槽位】
    //
    //   原来只有一组手调值，P9=1 之后板子完全忽略运动模式表，
    //   于是"调完深蹲再调跳绳"会把深蹲那组值覆盖掉 —— 这是个坑。
    //
    //   现在改成：三个模式各有一个槽位，串口命令写【当前模式】那个槽。
    //   某个模式从没被手调过（touched=0）时，仍然用运动模式表的值。
    //   所以按 KEY1/KEY2 切模式时，手调值会跟着模式走，不再互相覆盖。
    //------------------------------------------------------------------
    input  wire [2:0]  I_mode,           // 当前运动模式（来自 sport_mode）0..4
    input  wire [1:0]  I_sm_use_y0,      // 判据源（未手调时的回退）0=Σy 1=y0 2=xc
    input  wire [8:0]  I_sm_hold,
    input  wire [7:0]  I_sm_refr,
    input  wire [7:0]  I_sm_tol,
    input  wire [24:0] I_sm_min_amp,
    // 参数输出
    output reg  [7:0]  O_diff_th,
    output reg  [7:0]  O_gray_lo,
    output reg  [7:0]  O_gray_hi,
    output reg  [7:0]  O_proj_th,
    output reg  [24:0] O_min_amp,
    output reg  [8:0]  O_hold,
    output reg  [7:0]  O_refractory,
    output reg  [7:0]  O_rhythm_tol,
    // 清零：1 拍脉冲（接 jump_counter 的 I_clear）
    output reg         O_clear,
    // 判据来源选择（2026-10-14 新增）：0 = Σy（原行为）  1 = 头顶 y0（深蹲/开合跳更准）
    //   命令：P8=1 切到头顶，P8=0 切回 Σy
    //   深蹲实测：Σy 数成 24，头顶数成 16（真值 16）—— 见 design_top_wrapper 的注释
    //   2026-10-20：扩到 2 位 —— 0=Σy  1=y0  2=框中心 xc（往返跑用）
    output reg  [1:0]  O_use_y0,
    // 边缘检测阈值（2026-10-23 新增）：P11，接 enhance 的 I_edge_th
    //   越小越敏感（噪点多），越大只要强边缘（可能全黑）。默认 10。
    output reg  [7:0]  O_edge_th,
    // 二值化阈值（2026-10-23 新增）：P12，接 enhance 的 I_bin_th。默认 100。
    output reg  [7:0]  O_bin_th,
    // 边缘提取显示增益（2026-10-25 新增）：P13，接 cartoonize 的 I_ev_gain。默认 3。
    //   控制第 12 档（边缘提取）的画面亮度：edge_bt = edge_val × 本值
    output reg  [3:0]  O_ev_gain,
    // 卡通化描边阈值（2026-10-26 新增）：P14，接 cartoonize 的 I_edge_th。默认 65。
    //   第 11 档（动漫画）的描边灵敏度：e > 本值 就画黑线
    //   小 = 线多（眼睛等小细节也能出来，但噪声也多）
    //   大 = 线少（只要强轮廓）
    output reg  [7:0]  O_cart_edge_th,
    //==========================================================================
    // ★★★ 2026-10-27：卡通化（滤镜第 11/13 档）的 6 个关键参数改成串口可调
    //
    // 背景
    //   这 6 个原来是 cartoonize.v 的 parameter（编译期常量），想调一次就得
    //   重新编译 20 分钟。用户反馈"调滤镜参数怎么调都不行"——不是方向错，
    //   是**根本调不了**。
    //
    // 默认值对齐参考工程 `donghua - 2`（那版是调好的成品）：
    //   清晰锐利 + 颜色鲜艳 + 无黑描边
    //
    // 想回到"1013 版"观感（细量化 + 纯黑描边、轮廓最明显）：
    //   P15=7  P16=0  P18=0  P19=1
    //==========================================================================
    // P15 量化档位 0~8：8=不量化（最清晰），越小色块越粗
    output reg  [3:0]  O_quant_hi,
    // P16 锐化强度：16=关闭，40≈1.5x，48=2x
    output reg  [7:0]  O_k_us_q4,
    // P17 饱和度增益：1=不变，2/3/4=越来越艳
    output reg  [3:0]  O_sat_k,
    // P18 饱和度开关：0=关 1=开
    output reg         O_sat_en,
    // P19 描边暗化档：0=关闭（画面不变暗）1=纯黑 2=半暗 3=更暗
    output reg  [1:0]  O_edge_dark,
    // P20 对比度：16=关闭，越大越强
    output reg  [7:0]  O_contrast_q4,
    // ★ 2026-10-27：enhance 模式1（提亮/自动增亮）的 2 个参数
    // P21 提亮强度：0~7，越大越亮（原 LIFT_SHIFT=2）
    output reg  [2:0]  O_lift_shift,
    // P22 提亮模式饱和度增益：1~4（原 SAT_K=2）
    output reg  [2:0]  O_enh_sat_k,
    // ★ 2026-10-29：背景自适应速度（P23）2~5，默认 3
    //   控制轮廓"贴合速度"：3=0.13s（快）4=0.27s（中）5=0.5s（慢，拖影明显）
    output reg  [3:0]  O_bg_shift,
    // ★ 2026-10-29：帧差法阈值（P24），默认 12
    //   SW4 打开帧差法时生效；前景 = 背景相减 OR 帧差
    output reg  [7:0]  O_fd_th,
    // ★ 2026-10-30：色块识别（target_detect）的 5 个阈值，P25~P29
    //   ⚠ 队友原方案用的是 P23~P27，和我们的 BG_SHIFT(P23)/FD_TH(P24) 冲突，
    //     所以整体后移到 P25~P29
    output reg  [7:0]  O_tgt_orange_th,      // P25 红色 r 下限，默认 70
    output reg  [15:0] O_tgt_min_pix,        // P26 最小 core 数，默认 15
    output reg  [7:0]  O_tgt_blk_th,         // P27 黑色 mx 上限，默认 28
    output reg  [7:0]  O_tgt_vivid_sat,      // P28 蓝色 chroma 下限，默认 45
    output reg  [7:0]  O_tgt_orange_rmin,    // P29 红色 chroma 下限，默认 45
    // 参数来源选择（2026-10-15 新增）：0 = 用【运动模式表】（按键选运动）
    //                                1 = 用【串口手调值】（P4~P8 生效）
    //   命令：P9=1 进手动模式（现场微调用），P9=0 回运动表模式
    //   默认 0 —— 上电就是"按键选运动、参数自动"，符合日常使用
    output reg         O_manual,
    // DIFF_TH 是否被【P0 明确设置过】（2026-10-16 新增）
    //
    //   以前 DIFF_TH 的来源仲裁用的是 O_any_cmd（"收到过任何命令"）：
    //       S_diff_th = O_any_cmd ? 串口值 : 拨码值
    //   结果：用户把拨码设成 24（不敏感），只要发一条 P3=3（改投影阈值），
    //   DIFF_TH 就被悄悄换成串口默认值 10 —— 灵敏度瞬间提高 2.4 倍，
    //   噪声全部变成前景，框暴涨到画面边缘。
    //   （更糟的是 UART 上的垃圾字节也可能把它顶掉。）
    //
    //   现在改成：只有【真的收到 P0=<值>】才让串口值覆盖拨码值。
    output reg         O_diff_set,
    // 参考线显示开关（2026-10-16 新增）：命令 P10=0 关线 / P10=1 开线
    //   给用户一个"一键排除横线"的手段，不用重新编译。
    output reg         O_line_en,
    // 诊断：最近收到的字节 + 有效脉冲（可以接到 OSD 上，方便确认串口通没通）
    output reg  [7:0]  O_last_byte,
    output reg         O_last_pulse,
    // 已经收到过至少一条有效命令（PC 端可据此判断"串口通了"）
    output reg         O_any_cmd
);

    //-------------------------------------------------------------------------
    // 解析状态机
    //
    // ⚠ 2026-10-16 加了一个 ST_R 状态，原因见下面的"单字节 R 事故"说明
    //-------------------------------------------------------------------------
    localparam ST_IDLE = 2'd0,
               ST_IDX  = 2'd1,
               ST_VAL  = 2'd2,
               ST_R    = 2'd3;   // 收到 'R'，等换行确认（不立刻执行）

    reg [1:0]  st;
    reg [7:0]  idx;          // 参数序号
    reg [19:0] val;          // 数值累加器（20 位够放 MIN_AMP）

    //------------------------------------------------------------------
    // 三套手调参数（按运动模式索引）+ 每套的"是否被手调过"标志
    //------------------------------------------------------------------
    // 2026-10-19：模式 3 -> 5；2026-10-20：5 -> 6（加往返跑），槽位跟着扩到 6 组
    //   ⚠ 槽位数必须 >= 模式数！M_RUN=5 时索引 [5]，数组必须是 [0:5]
    reg [24:0] sl_min_amp [0:5];
    reg [8:0]  sl_hold    [0:5];
    reg [7:0]  sl_refr    [0:5];
    reg [7:0]  sl_tol     [0:5];
    reg [1:0]  sl_use_y0  [0:5];
    reg [5:0]  touched;

    // 输出 = 当前模式的槽位（没调过就用运动模式表的值）
    always @(*) begin
        O_min_amp    = touched[I_mode] ? sl_min_amp[I_mode] : I_sm_min_amp;
        O_hold       = touched[I_mode] ? sl_hold[I_mode]    : I_sm_hold;
        O_refractory = touched[I_mode] ? sl_refr[I_mode]    : I_sm_refr;
        O_rhythm_tol = touched[I_mode] ? sl_tol[I_mode]     : I_sm_tol;
        O_use_y0     = touched[I_mode] ? sl_use_y0[I_mode]  : I_sm_use_y0;
    end

    // 乘 10 加 digit：val*10 = (val<<3) + (val<<1)
    wire [19:0] val_x10 = {val, 3'b000} + {val, 1'b0};

    wire        is_digit = (I_rx_data >= 8'h30) && (I_rx_data <= 8'h39);
    wire [3:0]  digit    = I_rx_data - 8'h30;
    wire        is_nl    = (I_rx_data == 8'h0A) || (I_rx_data == 8'h0D);
    wire        is_eq    = (I_rx_data == 8'h3D);                  // '='
    wire        is_p     = (I_rx_data == 8'h50) || (I_rx_data == 8'h70);  // 'P' / 'p'
    wire        is_r     = (I_rx_data == 8'h52) || (I_rx_data == 8'h72);  // 'R' / 'r'

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            st           <= ST_IDLE;
            idx          <= 8'd0;
            val          <= 20'd0;
            O_diff_th    <= DEF_DIFF_TH;
            O_gray_lo    <= DEF_GRAY_LO;
            O_gray_hi    <= DEF_GRAY_HI;
            O_proj_th    <= DEF_PROJ_TH;
            // 五个分模式参数改成槽位存储，复位值不在这里赋
            // （输出由上面的 always @(*) 组合选择）
            sl_min_amp[0] <= 25'd0;  sl_hold[0] <= 9'd0;  sl_refr[0] <= 8'd0;
            sl_tol[0] <= 8'd0;       sl_use_y0[0] <= 2'd0;
            sl_min_amp[1] <= 25'd0;  sl_hold[1] <= 9'd0;  sl_refr[1] <= 8'd0;
            sl_tol[1] <= 8'd0;       sl_use_y0[1] <= 2'd0;
            sl_min_amp[2] <= 25'd0;  sl_hold[2] <= 9'd0;  sl_refr[2] <= 8'd0;
            sl_tol[2] <= 8'd0;       sl_use_y0[2] <= 2'd0;
            sl_min_amp[3] <= 25'd0;  sl_hold[3] <= 9'd0;  sl_refr[3] <= 8'd0;
            sl_tol[3] <= 8'd0;       sl_use_y0[3] <= 2'd0;
            sl_min_amp[4] <= 25'd0;  sl_hold[4] <= 9'd0;  sl_refr[4] <= 8'd0;
            sl_tol[4] <= 8'd0;       sl_use_y0[4] <= 2'd0;
            sl_min_amp[5] <= 25'd0;  sl_hold[5] <= 9'd0;  sl_refr[5] <= 8'd0;
            sl_tol[5] <= 8'd0;       sl_use_y0[5] <= 2'd0;
            touched      <= 6'b000000;   // 都没手调过 -> 全部跟运动模式表
            O_manual     <= 1'b0;          // 默认：用运动模式表（按键选运动）
            O_line_en    <= 1'b1;          // 默认：显示参考线
            O_edge_th    <= 8'd10;         // 边缘阈值（P11）
            O_bin_th     <= 8'd125;        // 二值化阈值（P12）—— 2026-10-28 用户实测定稿 125（原 140/67 均偏黑）
            O_ev_gain    <= 4'd3;          // 边缘提取增益（P13）
            // ★ 2026-10-28：85 → 15。原因：档位 10 改成「二值化边缘」后也用它，
            //   而 edge_val = (|gx|+|gy|)×3/16，阈值 85 需要原始梯度 453（几乎满量程），
            //   普通文字边缘（灰度差 50~150）只有 9~28 → 全黑。
            //   15 对应原始梯度 80，能勾出文字/物体边缘，平坦墙面（梯度 2~5 → 1 左右）不误判。
            //   档位 11 的卡通描边默认 I_edge_dark=0 不用这个阈值，改小不影响它。
            O_cart_edge_th <= 8'd8;        // P14 描边阈值（档位10/11 共用）—— 2026-10-28 用户定稿 8（线多，覆盖更全）
            // ★ 2026-10-27：P15~P20 卡通化关键参数，默认对齐参考工程 donghua-2
            O_quant_hi     <= 4'd6;        // P15 量化档位：6 = 步长 4（明显色块，动漫画核心）
            O_k_us_q4      <= 8'd40;       // P16 锐化 40 ≈ 1.5x（16=关闭）
            O_sat_k        <= 4'd2;        // P17 饱和度增益 2（3 会把色偏放大成青绿，1 太灰）
            O_sat_en       <= 1'b1;        // P18 饱和度开启
            O_edge_dark    <= 2'd1;        // P19 描边暗化：1 = 纯黑描边（动漫画必须有黑边）
            O_contrast_q4  <= 8'd16;       // P20 对比度 16 = 关闭
            O_lift_shift   <= 3'd3;        // P21 提亮强度（与顶层原 LIFT_SHIFT=3 一致）
            O_enh_sat_k    <= 3'd2;        // P22 提亮模式饱和度（原 SAT_K=2）
            O_bg_shift     <= 4'd3;        // P23 背景自适应速度（3=0.13s，贴合快）
            O_fd_th        <= 8'd12;       // P24 帧差阈值（SW4 打开帧差法时生效）
            // ★ 2026-10-30：色块识别阈值（P25~P29）
            O_tgt_orange_th   <= 8'd70;    // P25 红色 r 下限
            O_tgt_min_pix     <= 16'd15;   // P26 最小 core 数
            O_tgt_blk_th      <= 8'd28;    // P27 黑色 mx 上限
            O_tgt_vivid_sat   <= 8'd45;    // P28 蓝色 chroma 下限
            O_tgt_orange_rmin <= 8'd45;    // P29 红色 chroma 下限
            O_diff_set   <= 1'b0;          // 默认：DIFF_TH 用拨码开关值
            O_clear      <= 1'b0;
            O_last_byte  <= 8'd0;
            O_last_pulse <= 1'b0;
            O_any_cmd    <= 1'b0;
        end
        else begin
            O_clear      <= 1'b0;
            O_last_pulse <= I_rx_valid;

            if (I_rx_valid) begin
                O_last_byte <= I_rx_data;

                case (st)
                    //---------------------------------------------------------
                    // 等命令首字符
                    //---------------------------------------------------------
                    ST_IDLE: begin
                        if (is_p) begin
                            st  <= ST_IDX;
                            idx <= 8'd0;
                            val <= 20'd0;
                        end
                        else if (is_r) begin
                            // ⚠ 2026-10-16 修复：以前这里【立刻】执行清零并置 any_cmd，
                            //   导致 UART 线上任何一个 0x52('R')/0x72('r') 字节都会：
                            //     ① 清零计数
                            //     ② 永久置位 O_any_cmd -> DIFF_TH 从拨码值被换成串口默认值
                            //   如果拨码设的是 24（不敏感）而串口默认是 10，
                            //   灵敏度会突然提高 2.4 倍 -> 噪声变前景 -> 框暴涨到画面边缘。
                            //   实测症状：人在右边时框突然连到最左边、变成一个大框。
                            //   现在改成"等换行确认"，单独的 'R' 不再有任何副作用。
                            st <= ST_R;
                        end
                    end

                    //---------------------------------------------------------
                    // 收到 'R' 后等换行；只有真正 "R\n" 才算清零命令
                    //---------------------------------------------------------
                    ST_R: begin
                        if (is_nl) begin
                            st        <= ST_IDLE;
                            O_clear   <= 1'b1;
                            O_any_cmd <= 1'b1;
                        end
                        else if (!is_r) begin
                            st <= ST_IDLE;      // 不是 'R'+换行，丢弃
                        end
                        // 连续的 'R' 继续等待换行
                    end

                    //---------------------------------------------------------
                    // 收序号：数字累加，遇到 '=' 转去收数值
                    //---------------------------------------------------------
                    ST_IDX: begin
                        if (is_digit) begin
                            idx <= (idx > 8'd25) ? 8'd25 : (idx * 8'd10 + {4'b0, digit});
                        end
                        else if (is_eq) begin
                            st  <= ST_VAL;
                            val <= 20'd0;
                        end
                        else if (is_nl) begin
                            st <= ST_IDLE;          // 格式不全，丢弃
                        end
                    end

                    //---------------------------------------------------------
                    // 收数值：数字累加，遇到换行才应用（避免收到一半就生效）
                    //---------------------------------------------------------
                    ST_VAL: begin
                        if (is_digit) begin
                            val <= val_x10 + {16'b0, digit};
                        end
                        else if (is_nl) begin
                            st        <= ST_IDLE;
                            O_any_cmd <= 1'b1;
                            case (idx)
                                8'd0: begin
                                          O_diff_th  <= val[7:0];
                                          O_diff_set <= 1'b1;   // 只有 P0 才置位
                                      end
                                8'd1: O_gray_lo    <= val[7:0];
                                8'd2: O_gray_hi    <= val[7:0];
                                8'd3: O_proj_th    <= val[7:0];
                                // P4~P8 写【当前运动模式】的槽位
                                8'd4: begin
                                          sl_min_amp[I_mode] <= {5'b0, val};
                                          touched[I_mode]    <= 1'b1;
                                      end
                                8'd5: begin
                                          sl_hold[I_mode] <= val[8:0];
                                          touched[I_mode] <= 1'b1;
                                      end
                                8'd6: begin
                                          sl_refr[I_mode] <= val[7:0];
                                          touched[I_mode] <= 1'b1;
                                      end
                                8'd7: begin
                                          sl_tol[I_mode]  <= val[7:0];
                                          touched[I_mode] <= 1'b1;
                                      end
                                // P8 = 判据来源：0=Σy  非0=头顶 y0
                                8'd8: begin
                                          sl_use_y0[I_mode] <= val[1:0];
                                          touched[I_mode]   <= 1'b1;
                                      end
                                // P9 = 参数来源：0=运动模式表  非0=串口手调
                                8'd9: O_manual     <= (val != 20'd0);
                                // P10 = 参考线开关：0=关闭  非0=显示（默认显示）
                                //   用于让用户自己验证"框/线抖动是不是横线造成的"：
                                //   P10=0 把两条线关掉，如果框还是抖 -> 和线无关。
                                8'd10: O_line_en   <= (val != 20'd0);
                                // P11 = 边缘检测阈值（模式10）：越小越敏感
                                8'd11: O_edge_th   <= val[7:0];
                                // P12 = 二值化阈值（模式5）：越小越白
                                8'd12: O_bin_th    <= val[7:0];
                                // P13 = 边缘提取显示增益（第12档亮度）
                                8'd13: O_ev_gain   <= val[3:0];
                                // P14 = 卡通化描边阈值（第11档），小=线多 大=线少
                                8'd14: O_cart_edge_th <= val[7:0];
                                // ★ 2026-10-27：P15~P20 卡通化实时调参
                                8'd15: O_quant_hi    <= val[3:0];   // 0~8（8=不量化）
                                8'd16: O_k_us_q4     <= val[7:0];   // 锐化 16=关
                                8'd17: O_sat_k       <= val[3:0];   // 饱和增益 1~4
                                8'd18: O_sat_en      <= (val != 20'd0);
                                8'd19: O_edge_dark   <= val[1:0];   // 0=关 1=纯黑 2=半暗 3=更暗
                                8'd20: O_contrast_q4 <= val[7:0];   // 对比度 16=关
                                // ★ enhance 模式1（提亮）实时调参
                                8'd21: O_lift_shift  <= val[2:0];   // 0~7 越大越亮
                                8'd22: O_enh_sat_k   <= val[2:0];   // 1~4 饱和增益
                                8'd23: O_bg_shift    <= val[3:0];   // ★ P23 背景自适应速度 2~5（3=贴合快）
                                8'd24: O_fd_th       <= val[7:0];   // ★ P24 帧差阈值（SW4 打开帧差法时生效）
                                // ★ 2026-10-30：色块识别阈值（P25~P29）
                                8'd25: O_tgt_orange_th   <= val[7:0];    // P25 红色 r 下限
                                8'd26: O_tgt_min_pix     <= val[15:0];   // P26 最小 core 数
                                8'd27: O_tgt_blk_th      <= val[7:0];    // P27 黑色 mx 上限
                                8'd28: O_tgt_vivid_sat   <= val[7:0];    // P28 蓝色 chroma 下限
                                8'd29: O_tgt_orange_rmin <= val[7:0];    // P29 红色 chroma 下限
                                default: ;              // 序号非法，忽略
                            endcase
                        end
                        // 其它字符（空格等）忽略，继续等换行
                    end

                    default: st <= ST_IDLE;
                endcase
            end
        end
    end

endmodule


//=============================================================================
//  sport_mode  --  运动模式表（按键切换 + 每种运动一套参数）
//
//  ⚠ 2026-10-15：这个模块【故意放在 param_ctrl.v 里面】，不单独建文件。
//
//  原因（踩过三次的坑）
//    TD 只在【打开工程】时读 camera_to_dsi_display.al 的文件清单，
//    但每次编译都会重读文件【内容】。
//    所以新建 .v 文件 + 外部改 .al 是无效的 —— TD 内存里没有这个文件，
//    综合时会报 "xxx is a black box"，整个 Run 直接失败。
//    （已经因此失败过三次：uart_rx/param_ctrl、line_tracker、sport_mode）
//
//    把新模块塞进【已经登记过的文件】里就永远不会有这个问题 ——
//    因为 TD 会重读这个文件的内容，自然就看到了新模块。
//
//  为什么需要按运动区分参数
//  ---------------------------------------------------------------------------
//  跳绳、深蹲、开合跳的物理特征完全不同，用同一套判据必然有的准有的不准：
//
//    运动     Σy 判据               头顶 y0 判据          主频
//    ----------------------------------------------------------------
//    跳绳     面积不变 -> 单峰 OK    也能用               1.5~3 Hz
//    深蹲     面积剧变 -> 双峰 X     只反映高度 -> OK     0.3~0.8 Hz
//    开合跳   面积变化最大 -> X      也能用               1~2 Hz
//
//  ★ 判据源为什么要区分
//     Σy = 质心行号 × 面积。蹲起时"质心往下"和"面积变小"互相抵消，
//     导致 Σy 非单调 —— 一个蹲起出现两个谷，16 个数成 24。
//     头顶 y0 只反映"最高点在哪"，不受面积影响 -> 单峰 -> 数得准。
//     但跳绳时面积本来就稳，Σy 的参数调了很久更成熟，所以保留 Σy。
//
//  ★ 参数是【用真实数据扫出来的】，不是拍脑袋定的
//     数据 = tools/jump1.csv（29.6 秒 16 个蹲起）
//     扫 HOLD/REFRACTORY 网格找最接近 16 的组合 -> HOLD=100/REF=50 得 15 ✓
//     踩过的坑：HOLD=130（2.17s）会把包络"冻住"，CNT 反而掉到 8。
//
//  资源：3 套参数 × 6 个寄存器 ≈ 60 DFF + 组合译码 ≈ 40 LUT，0 DSP
//=============================================================================

module sport_mode (
    input  wire        I_clk,
    input  wire        I_rst_n,
    input  wire        I_btn_next,     // KEY1：下一个模式
    input  wire        I_btn_prev,     // KEY2：上一个模式

    output reg  [2:0]  O_mode,         // 0=跳绳 1=深蹲 2=开合跳 3=仰卧起坐 4=俯身摸脚尖
    // 判据源：0 = Σy   1 = 头顶 y0×128   2 = 框中心 xc×128（往返跑）
    output reg  [1:0]  O_use_y0,
    // 时间常数与幅度门（当前模式的值）
    output reg  [8:0]  O_hold,
    output reg  [7:0]  O_refractory,
    output reg  [7:0]  O_rhythm_tol,
    output reg  [24:0] O_min_amp
);

    //-------------------------------------------------------------------------
    // ⚠ MIN_AMP 的量纲跟随判据源：
    //   · Σy 模式    ：实测动态范围约 9665（p5~p95）
    //   · y0×128 模式：实测动态范围约 5632
    // 所以两种源的 MIN_AMP 不能直接互换，表里分别给。
    //-------------------------------------------------------------------------
    localparam [2:0] M_ROPE  = 3'd0,   // 跳绳
                     M_SQUAT = 3'd1,   // 深蹲
                     M_JACK  = 3'd2,   // 开合跳
                     M_ABS   = 3'd3,   // 仰卧起坐（2026-10-19 新增）
                     M_TOE   = 3'd4,   // 俯身摸脚尖（2026-10-19 新增）
                     M_RUN   = 3'd5;   // 往返跑（2026-10-20 新增）

    reg [2:0]  mode;

    // 中间信号（组合译码用）
    reg [1:0]  use_y0;
    reg [8:0]  hold;  reg [7:0] refr, tol;
    reg [24:0] min_amp;

    // 按键：循环切换（KEY1 下一个 / KEY2 上一个）
    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n)
            mode <= M_ROPE;                        // 上电默认：跳绳（与改动前一致）
        else if (I_btn_next)
            mode <= (mode >= M_RUN) ? M_ROPE : mode + 3'd1;
        else if (I_btn_prev)
            mode <= (mode == M_ROPE) ? M_RUN : mode - 3'd1;
    end

    // 模式 -> 参数（组合译码，纯 LUT）
    always @(*) begin
        case (mode)
            //-------------------------------------------------------------
            // 跳绳：头顶判据，高频短周期
            //
            //   ⚠ 2026-10-15 从 Σy 改成头顶 y0。两个理由：
            //
            //   ① 【参考线与判据统一】
            //      屏幕上那两条青/橙参考线永远跟 y0（line_tracker 只吃 y0）。
            //      原来跳绳用 Σy 计数，于是切到跳绳模式时线是"误导"的：
            //      线描述的是头顶判据，实际计数却看 Σy，两者对不上。
            //
            //   ② 【实测证明改过去不会变差】
            //      跳绳时人整体上下移动、形状不变 -> 面积恒定。
            //      此时 Σy = 质心×面积，面积是常数，而质心 = 头顶 + 身高/2，
            //      所以 Σy 与 y0 只差一个线性变换，【信息量完全相同】。
            //      合成 2Hz/30 秒跳绳信号实测（tools/_test_rope_with_y0.py）：
            //        Σy   判据 -> 60/60 次 ✓
            //        y0   判据 -> 60/60 次 ✓
            //        Σy 与 y0 相关系数 0.999
            //      两者等价，所以统一到 y0 没有任何损失。
            //
            //   MIN_AMP 跟着换量纲：y0×128 的动态范围约 5632（Σy 约 9665），
            //   所以门限从 2500 降到 1800（约占 32%）。
            //
            //   ⚠ 2026-10-19 用真实跳绳数据重新标定（tune_rope_1019_1951.csv，
            //     1806 帧 / 29.5 秒，真值 30）：
            //       MIN_AMP 1800 -> 150（1.17 行）  峰值实测 29 行
            //       HOLD      25 -> 15              跳绳周期实测 54 帧（1.11 Hz）
            //       REFR      7  -> 15
            //       TOL       2  -> 15              间隔 47~61 帧，tol=max(27,15)=27 足够
            //     结果 29/30（CNT=RAW=29，节律门零拦截）。
            //     漏的 1 个原因：落地那一帧 y0 只维持 1 帧，被 4 点滑动平均抹平，
            //     不是参数问题（详见 memory/2026-10-19.md）。
            //     稳健性：REFRACTORY ±40% 全稳；MIN_AMP 120~150 稳；
            //             HOLD 必须接近 15（9/21 都会掉到 27）。
            //-------------------------------------------------------------
            M_ROPE: begin
                use_y0  = 2'd1;
                hold    = 8'd15;        // 0.25s @60fps（实测跳绳周期 54 帧）
                refr    = 8'd15;        // 0.25s
                // 2026-10-22 按实测最佳固化（tune_rope_1019_2103.csv）：
                //   TOL 15 -> 255（等于关闭节律门）。理由：跳绳 RAW 与 CNT 完全相等，
                //   事件检测零误检，节律门在此只会误杀真动作。
                //   MIN_AMP 150 -> 200（实测 200 时 47/48，150 时 29/30）。
                tol     = 8'd255;
                min_amp = 25'd200;
            end
            //-------------------------------------------------------------
            // 深蹲：头顶判据（避开双峰），慢速大周期
            //   HOLD=100 / REF=50 是实测最优（见文件头说明）
            //-------------------------------------------------------------
            M_SQUAT: begin
                use_y0  = 2'd1;
                // 2026-10-22 按实测最佳固化（tune_squat_1019_2021.csv，真值 16）：
                //   400/50/20/15 -> 16/16 ✓（峰值 38 行 = 4864）
                //   ⚠ 原值 1500/100/50/20 的 MIN_AMP 是实测值的 3.8 倍。
                //     之前"深蹲能用"是因为手调值在寄存器里，掉电回到 1500 就未必。
                hold    = 8'd50;        // 0.83s
                refr    = 8'd20;        // 0.33s
                tol     = 8'd15;
                min_amp = 25'd400;      // 实测幅度 4864 的 8%
            end
            //-------------------------------------------------------------
            // 开合跳：头顶判据，中速；幅度比深蹲小、比跳绳大
            //-------------------------------------------------------------
            M_JACK: begin
                use_y0  = 2'd1;
                // 2026-10-22 按实测最佳固化（tune_jack_1019_2022.csv，真值 16）：
                //   1200/80/20/15 -> 16/16 ✓（峰值 34 行 = 4352）
                //   ⚠ 之前长期记录"开合跳未验证"是错的 —— 10-19 20:22 已有 16/16 实证。
                hold    = 8'd80;        // 1.33s
                refr    = 8'd20;        // 0.33s
                tol     = 8'd15;
                min_amp = 25'd1200;     // 实测幅度 4352 的 28%
            end
            //-------------------------------------------------------------
            // 仰卧起坐（2026-10-19 新增）—— ⚠ 参数是【估算值，未真机验证】
            //
            //   判据：y0（头顶行号）。躺下 -> 坐起，头顶在画面里明显升高。
            //   幅度估算 30~40 行（= 3840~5120），取门限 1000（约 8 行）。
            //   周期 1.5~3 秒（90~180 帧），HOLD 取 70 覆盖半个周期。
            //
            //   ⚠ 取景前提：躺下时人必须还在画面内，且 area >= 16 格。
            //     人躺平后轮廓变"扁"，前景格数会明显减少；若屏幕上没框，
            //     说明 Y0_AREA_MIN=16 太高，需要降到 8~12。
            //
            //   ⚠ 与深蹲的区别：深蹲是站着上下，仰卧起坐是"躺->坐"，
            //     两者的 y0 都大幅变化，靠周期（深蹲 1.9s / 仰卧 2s）几乎分不开。
            //     演示时靠按键切模式，不指望自动识别。
            //-------------------------------------------------------------
            //   ⚠ 2026-10-20 实测标定（tune_abs_1020_2013.csv，1809 帧/29.6 秒，真值 12）：
            //     实测幅度 21.5 行 = 2752，周期 148 帧（2.47 秒）
            //     旧估算值 1000/70/45/25 在真机上只数出 1 个 —— HOLD=70 太短，
            //     amp 在动作间隔内衰减到门限以下，状态机反复复位。
            //     标定结果 400/120/20/25 数出 11/12（第一次动作因包络未建立而漏）。
            //     备选 300/150 时 RAW=12（事件全检测到），但 CNT 仍 11。
            //   ⚠ 这组参数是"尖峰"不是"平台"：HOLD ±20% 就会掉到 10。
            //     现场若数不准，先试 300/150，并让用户先做 1~2 个热身动作再清零。
            M_ABS: begin
                use_y0  = 2'd1;
                // 2026-10-22 按实测最佳固化（tune_abs_1020_2001.csv，真值 12）：
                //   300/100/50/10 -> 12/12 ✓（峰值 36 行 = 4608）
                //   另有一次 200/60/60/8 也是 12/12，两套都可用；
                //   取 300/100 是因为 HOLD 与上一版（120）接近，改动风险更小。
                hold    = 8'd100;       // 1.67s
                refr    = 8'd50;        // 0.83s
                tol     = 8'd10;
                min_amp = 25'd300;      // 实测幅度 4608 的 6.5%
            end
            //-------------------------------------------------------------
            // 俯身摸脚尖（2026-10-19 新增）—— ⚠ 参数是【估算值，未真机验证】
            //
            //   判据：y0。站立 -> 弯腰摸脚尖，头顶从约 30 行掉到约 80 行，
            //   幅度 40~50 行（5120~6400），是本项目里最好检测的动作之一。
            //   周期 2~4 秒（120~240 帧），很慢，所以 HOLD/REFRACTORY 都要大。
            //
            //   为什么这个最容易：弯腰时头顶位移占身高的 2/3，远超跳绳（29 行）
            //   和深蹲（62 行），信噪比最高。
            //-------------------------------------------------------------
            M_TOE: begin
                use_y0  = 2'd1;
                hold    = 8'd90;        // 1.5s，覆盖慢动作的半个周期
                refr    = 8'd70;        // 1.17s，防一次弯腰数两下
                tol     = 8'd35;        // 慢动作间隔本来就散
                min_amp = 25'd1200;     // 估算：幅度 40~50 行的 1/4
            end
            //-------------------------------------------------------------
            // 往返跑（2026-10-20 新增）—— ⚠ 参数是【估算值，未真机验证】
            //
            //   判据：**框中心 xc=(x0+x1)/2**，不是 y0！
            //   人左右跑时头顶高度几乎不变（1~3 行），y0 判据完全失效；
            //   而 xc 随人左右移动大幅摆动：3 m 处单程 3.35 m = 112 格。
            //
            //   为什么不用 Σx：Σx = area × 质心x，人前后移动会改 area，
            //   把左右位移淹没掉。框中心只取边界，不受面积影响。
            //
            //   参数估算：
            //     幅度 112 格 × 128 = 14336，MIN_AMP 取其 1/4 = 3500
            //     往返 6.69 m @2 m/s = 3.35 秒 = 201 帧
            //     HOLD/REFRACTORY 取半周期 100/80；转身有停顿，TOL 给 50
            //-------------------------------------------------------------
            //   ⚠ 2026-10-20 用户实跑反馈：速度读数只在 1.5 / 3.5 两个值之间跳，
            //     根因是 since_last 是 8 位、饱和在 255 帧（4.25 秒 = 1.57 m/s）。
            //     已把 since_last/prev_interval/O_interval 扩到 10 位（1023 帧 = 17 秒）。
            //     并加了"静止 400 帧后速度清零"，避免停下后一直显示旧值。
            M_RUN: begin
                use_y0  = 2'd2;         // 框中心 xc
                // 2026-10-20 用合成信号扫描后重定（原来 100/80/50/3500 完全数不出来）：
                //   5 个往返的期望值 4（第一次因包络未建立不计）
                //   HOLD=100 时各节奏 CNT 全是 0~2 —— 幅度在动作间隔内衰减，
                //   状态机反复复位。往返跑幅度恒定，HOLD 就该取大（几乎不衰减）。
                //   扫描结果：HOLD=400 在周期 1.5~7.7 秒（90~460 帧）全部 CNT=4 ✓
                //   而 8 位 HOLD 上限 255 只够覆盖到 2.7 秒，所以 HOLD 已扩到 9 位。
                // 2026-10-22 按真实数据扫描后固化（tune_run_1020_2115.csv，真值 5）：
                //   xc 峰峰 154 格（= 4.60 米单程），MIN_AMP 扫描结果：
                //     80/100/120/150 -> 5 ✓ | 200 -> 4 | 300 -> 3 | 500 -> 1 | 2000 -> 1
                //   ⇒ MIN_AMP 150 已是临界上限，原固件值 2000 会让往返跑完全失效（只数出 1 个）！
                //   HOLD：真实数据 20~400 全部 5/5（除 80 是 4）；合成扫描要求 >=260 才覆盖
                //         1.5~7.7 秒全节奏 → 取 300（两边都过，落在平台中央）
                //   REFRACTORY：20/30/40 掉到 4，60 才 5/5 → 必须 60
                hold    = 9'd300;       // 5.0s，兼顾慢节奏与峰值刷新
                refr    = 8'd60;        // 1.0s
                tol     = 8'd15;
                min_amp = 25'd150;      // 临界值，勿再调高
            end
            default: begin
                use_y0  = 2'd0;
                hold    = 8'd25;
                refr    = 8'd7;
                tol     = 8'd2;
                min_amp = 25'd2500;
            end
        endcase
    end

    // 输出打一拍（避免组合直通到 jump_counter 的输入）
    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            O_mode       <= M_ROPE;
            O_use_y0     <= 2'd0;
            O_hold       <= 9'd25;
            O_refractory <= 8'd7;
            O_rhythm_tol <= 8'd2;
            O_min_amp    <= 25'd2500;
        end
        else begin
            O_mode       <= mode;
            O_use_y0     <= use_y0;
            O_hold       <= hold;
            O_refractory <= refr;
            O_rhythm_tol <= tol;
            O_min_amp    <= min_amp;
        end
    end

endmodule


//=============================================================================
//  servo_pwm  --  一维舵机 PWM（2026-10-23 新增）
//
//  用途：摄像头云台左右跟随人体，对应选题指南扩展要求第 3 条「外部控制」
//
//  规格
//    50Hz（周期 20ms），脉宽 0.5~2.5ms 对应 -90°~+90°
//    50MHz 时钟：20ms = 1,000,000 计数；0.5ms = 25,000；2.5ms = 125,000
//
//  映射
//    I_pos（框中心 xc，0~159）-> duty = 25000 + xc x 512
//      xc=0   ->  25000 (0.50ms, -72°)
//      xc=79  ->  65448 (1.31ms, 约 0°)
//      xc=159 -> 106408 (2.13ms, +72°)
//    512 = 单个左移，0 DSP、约 10 LUT
//
//  保护
//    · 每帧最多动 STEP=1500 计数（约 2.4 格 / 4.3°）
//      全程 98580 计数走完约 66 帧（1.1 秒），跟得上人正常走动
//      ⚠ 初版写的 4 计数/帧要走 411 秒，舵机根本跟不上，2026-10-23 已修正
//    · 死区 DEAD=2000 计数（约 3.2 格）：框中心的小抖动不会让舵机来回摆
//    · I_en=0 时按同样步进回居中，不会突然甩动
//    · 中间量用 24 位，避免 (xc << 9) 在 17 位里被截断
//=============================================================================
module servo_pwm (
    input  wire        I_clk,
    input  wire        I_rst_n,
    input  wire        I_en,        // 1=跟随  0=回居中
    input  wire        I_valid,     // 每帧一个脉冲（motion_stats 的 O_valid）
    // ★ 2026-10-29：入参从"画面里的位置"改成"目标脉宽计数"
    //   原因见下面大段注释：位置->脉宽必须做【增量累积】，不能做绝对映射，
    //   否则摄像头能到达的角度会被画面宽度锁死（只有 ±43°）。
    //   累积在顶层做，本模块只负责把 duty 平滑地推过去。
    input  wire [17:0] I_duty_tgt,  // 目标脉宽计数，37,500(0.5ms) ~ 187,500(2.5ms)
    output reg         O_pwm,
    output wire [17:0] O_duty       // 当前脉宽计数（750 计数 = 0.01ms）
);
    //--------------------------------------------------------------------------
    // ⚠⚠ 2026-10-28 晚（三）：时钟基准修正（这是"舵机不动"的真正原因）
    //
    //   本模块原来整套常数都是按 50MHz 写的，但顶层接的是
    //   S_hdmi_pixel_clk = PLL 的 C4 = 75MHz。按 50MHz 写、跑 75MHz 的后果：
    //     CENTER 75000  -> 75000/75M  = 1.000ms  （应 1.5ms，整体偏了 -45°）
    //     34040         -> 0.454ms   （低于 0.5ms 下限，很多舵机干脆不响应）
    //     115448        -> 1.539ms   （远没到 2.5ms）
    //     PERIOD_CNT    -> 13.33ms = 75Hz（不是 50Hz）
    //   ⇒ 实际行程只有 0.45~1.54ms 且整体偏向一端，看起来就是"不动"或"只往一边走"。
    //
    //   按 75MHz 重算（1ms = 75,000 计数）：
    //     20ms  = 1,500,000 -> 需要 21 位（原来的 20 位根本装不下 20ms）
    //     0.5ms = 37,500 / 1.5ms = 112,500 / 2.5ms = 187,500 -> 需要 18 位
    //--------------------------------------------------------------------------
    localparam [20:0] PERIOD_CNT = 21'd1_499_999;  // 20ms @75MHz -> 50Hz
    localparam [17:0] CENTER     = 18'd112_500;    // 1.5ms
    localparam [17:0] STEP       = 18'd2_250;      // 每帧最大步进（约 2.7°）
    localparam [17:0] DEAD       = 18'd3_000;      // 死区（约 3.2 格）

    //--------------------------------------------------------------------------
    // ★★ 2026-10-29：为什么必须改成【增量式】（这是"只能小范围移动"的根因）
    //
    //   原来的写法（绝对映射）
    //     duty = 145780 - xc × 416        xc 是人在画面里的位置 0~159
    //
    //   问题：xc=80（人在正中）时 duty 恒等于 112500，也就是舵机机械中位。
    //   也就是说"人回到画面正中"必然要求"摄像头回到中位"——这两件事被绑死了。
    //   于是摄像头能到达的角度被 xc 的取值范围锁死：
    //     xc=0 -> 1.94ms，xc=159 -> 1.06ms，总共只有 ±43°
    //   人走一两步，摄像头转到头；再走，xc 还是 0，duty 还是 1.94ms，就不动了。
    //   （用户实测："左移一步会跟随，右移一步也可以，再多就不行了"）
    //
    //   正确做法（增量式 / 积分控制）
    //     新角度 = 旧角度 - (xc - 80) × 416
    //   每次触发只把"当前角度"加上这一步的修正量，而不是重新算一个绝对角度。
    //   这样人一直往左走，角度就一直往左累加，摄像头能一路跟下去。
    //   限幅在 0.5ms ~ 2.5ms（±90°），覆盖整个舵机行程。
    //
    //   累积逻辑在 design_top_wrapper.v 里做（S_srv_cmd），本模块只做平滑推近：
    //     · 每帧最多走 STEP=2250 计数（0.03ms，约 2.7°）
    //     · 距目标不到 DEAD=3000 计数就不动（防抖）
    //   ⚠ 这四个 localparam 在上面已经声明过（741~744 行），这里不能再写一遍，
    //     否则 TD 报 "already declared" 语法错误。
    //--------------------------------------------------------------------------

    reg [20:0] cnt;
    reg [17:0] duty;

    assign O_duty = duty;       // 给顶层做 OSD 显示用，不影响 PWM 本身

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            cnt   <= 21'd0;
            duty  <= CENTER;
            O_pwm <= 1'b0;
        end
        else begin
            if (cnt >= PERIOD_CNT) cnt <= 21'd0;
            else                   cnt <= cnt + 21'd1;

            if (!I_en) begin
                if (duty > CENTER + STEP)      duty <= duty - STEP;
                else if (duty + STEP < CENTER) duty <= duty + STEP;
                else                           duty <= CENTER;
            end
            else if (I_valid) begin
                if (I_duty_tgt > duty + DEAD) begin
                    duty <= (I_duty_tgt - duty > STEP) ? (duty + STEP) : I_duty_tgt;
                end
                else if (I_duty_tgt + DEAD < duty) begin
                    duty <= (duty - I_duty_tgt > STEP) ? (duty - STEP) : I_duty_tgt;
                end
                // 差值在死区内：保持不动，滤掉位置的小抖动
            end

            O_pwm <= (cnt < duty);
        end
    end
endmodule


    //    都不是 8 的倍数（不是 sample 拍），再到下一行 x=0 才重新采样 ——
    //    中间有 7 拍空档。所以可以把「收段」和「band 合并」分别推到后两拍做，
    //    把一条 32 级、16 个加法器的超长组合链拆成三级流水。
    //
    //    帧末同理：frame_end 在 x_cnt=1279，下一拍就是新帧第一格，
    //    「收 band」和「门限判定」分两拍做，不影响结果。
    //-------------------------------------------------------------------------
    reg row_end_d1, row_end_d2;
    reg frame_end_d1, frame_end_d2;

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            row_end_d1   <= 1'b0;
            row_end_d2   <= 1'b0;
            frame_end_d1 <= 1'b0;
            frame_end_d2 <= 1'b0;
        end
        else begin
            row_end_d1   <= row_end;
            row_end_d2   <= row_end_d1;
            frame_end_d1 <= frame_end;
            frame_end_d2 <= frame_end_d1;
        end
    end

    //-------------------------------------------------------------------------
    // 4. 三类并行流式状态机
    //-------------------------------------------------------------------------
    wire        y_pass, d_pass, w_pass;
    wire [10:0] y_gcore, d_gcore, w_gcore;


    v7_class #(
        .MIN_CORE ( BLUE_MIN_CORE ), .MIN_W ( BLUE_MIN_W ),
        .MAX_W    ( BLUE_MAX_W    ), .MIN_H ( BLUE_MIN_H ),
        .MAX_H    ( BLUE_MAX_H    ), .DENS_K( DENS_K_BR ),
        .GAPX     ( GAPX ), .VGAP ( VGAP ),
        .PROJ_TH  ( PROJ_TH ), .HOLD_N( HOLD_N )
    ) u_cls_blue (
        .I_clk( I_clk ), .I_rst_n( I_rst_n ),
        .I_sample( sample ),
        .I_row_end_d1( row_end_d1 ), .I_row_end_d2( row_end_d2 ),
        .I_frame_end( frame_end ), .I_frame_end_d1( frame_end_d1 ),
        .I_sx( s_x ), .I_sy( s_y ),
        .I_hit( y_hit ), .I_core( y_core ), .I_min_core( GLOBAL_MIN_CORE ),
        // ★ 2026-10-30 去掉小船后，三类重新映射到原有端口：
        //   O_orange_* = 蓝色物体, O_vivid_* = 黑色物体, O_dark_* = 红色物体
        .O_valid( O_orange_valid ),
        .O_x0( O_orange_x0 ), .O_x1( O_orange_x1 ),
        .O_y0( O_orange_y0 ), .O_y1( O_orange_y1 ),
        .O_pass( y_pass ), .O_gcore( y_gcore )
    );

    v7_class #(
        .MIN_CORE ( DARK_MIN_CORE ), .MIN_W ( DARK_MIN_W ),
        .MAX_W    ( DARK_MAX_W    ), .MIN_H ( DARK_MIN_H ),
        .MAX_H    ( DARK_MAX_H    ), .DENS_K( DENS_K ),
        .GAPX     ( GAPX ), .VGAP ( VGAP ),
        .PROJ_TH  ( PROJ_TH ), .HOLD_N( HOLD_N )
    ) u_cls_dark (
        .I_clk( I_clk ), .I_rst_n( I_rst_n ),
        .I_sample( sample ),
        .I_row_end_d1( row_end_d1 ), .I_row_end_d2( row_end_d2 ),
        .I_frame_end( frame_end ), .I_frame_end_d1( frame_end_d1 ),
        .I_sx( s_x ), .I_sy( s_y ),
        .I_hit( d_hit ), .I_core( d_core ), .I_min_core( GLOBAL_MIN_CORE ),
        .O_valid( O_vivid_valid ),
        .O_x0( O_vivid_x0 ), .O_x1( O_vivid_x1 ),
        .O_y0( O_vivid_y0 ), .O_y1( O_vivid_y1 ),
        .O_pass( d_pass ), .O_gcore( d_gcore )
    );

    v7_class #(
        .MIN_CORE ( RED_MIN_CORE ), .MIN_W ( RED_MIN_W ),
        .MAX_W    ( RED_MAX_W    ), .MIN_H ( RED_MIN_H ),
        .MAX_H    ( RED_MAX_H    ), .DENS_K( DENS_K_BR ),
        .GAPX     ( GAPX ), .VGAP ( VGAP ),
        .PROJ_TH  ( PROJ_TH ), .HOLD_N( HOLD_N )
    ) u_cls_red (
        .I_clk( I_clk ), .I_rst_n( I_rst_n ),
        .I_sample( sample ),
        .I_row_end_d1( row_end_d1 ), .I_row_end_d2( row_end_d2 ),
        .I_frame_end( frame_end ), .I_frame_end_d1( frame_end_d1 ),
        .I_sx( s_x ), .I_sy( s_y ),
        .I_hit( rl_hit ), .I_core( rl_core ), .I_min_core( GLOBAL_MIN_CORE ),
        .O_valid( O_dark_valid ),
        .O_x0( O_dark_x0 ), .O_x1( O_dark_x1 ),
        .O_y0( O_dark_y0 ), .O_y1( O_dark_y1 ),
        .O_pass( w_pass ), .O_gcore( w_gcore )
    );

    //-------------------------------------------------------------------------
    // 5. 胜者类别（本帧过门限的三类里，core 最多的那个）
    //    都不过门限则保持上一帧的选择
    //    frame_end_d2 = frame_end+2 拍，此时三类 O_pass/O_gcore 已稳定
    //-------------------------------------------------------------------------
    // 没 pass 的类把 gcore 屏蔽成 0，避免"没过门限但 core 数大"的类抢走胜者
    wire [10:0] yg = y_pass ? y_gcore : 11'd0;
    wire [10:0] dg = d_pass ? d_gcore : 11'd0;
    wire [10:0] wg = w_pass ? w_gcore : 11'd0;
    wire        any_pass = y_pass | d_pass | w_pass;

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) O_win_class <= 2'd0;
        else if (frame_end_d2 && any_pass) begin
            if      ((yg > 11'd0) && (yg >= dg) && (yg >= wg)) O_win_class <= 2'd0;
            else if ((dg > 11'd0) && (dg >= wg))               O_win_class <= 2'd1;
            else                                               O_win_class <= 2'd2;
        end
    end

endmodule


//=============================================================================
// v7_class -- 单类流式检测状态机（三类各例化一份）
//
//  ★ 五级流水（每级 1 拍，全部落在行间/帧间的空闲拍里，不影响结果）
//    A  sample 拍       : 行内 run 累加 / 段自然结束时结算 best
//    B  row_end+1 拍    : 段延伸到行末 -> 结算 best
//    C  row_end+2 拍    : 用 best 做 band 合并（重叠并 / 空行超限收）
//    D  frame_end 拍    : 收当前 band -> 候选（取 core 最大）
//    E  frame_end+1 拍  : 门限判定 + 帧间保持 + 输出
//
//  ★ 为什么必须拆流水（2026-10-29 实测）
//    原来把 A~E 串成一个 always @(*) 组合链，综合出 32 级逻辑、16 个加法器，
//    布局后 Setup WNS = -10.0ns（要求 13.333ns，实际 23.1ns，FMAX 42.8MHz）。
//    布线器为修时序反复 rip-up/reroute，一次编译 50 分钟还不收敛。
//    拆成五级后每级只有 1~2 个加法器，路径回到 5ns 以内。
//
//  ★ 位宽压缩（省资源）
//    run_len/run_core/best_*  : 9 -> 8 位（最大 160 < 256）
//    bcore/cand_core          : 14 -> 11 位【饱和】计数
//        门限最大只要 K*MAX_W = 3*160 = 480，11 位能到 2047，余量 4 倍；
//        超过 2047 一律饱和（真实场景一类只有一个目标，碰不到）。
//        加法器/比较器从 14 位降到 11 位，720 个随机用例零差异。
//    seg_hi 用 9 位算、取低 8 位（段右端必然 <= 159）
//=============================================================================
module v7_class #(
    parameter [7:0] MIN_CORE = 8'd25,
    parameter [7:0] MIN_W    = 8'd4,
    parameter [7:0] MAX_W    = 8'd90,
    parameter [6:0] MIN_H    = 7'd4,
    parameter [6:0] MAX_H    = 7'd90,
    parameter [3:0] DENS_K   = 4'd3,   // 双轴密度系数 1/2/3（3 倍用加法实现，避免 DSP）
    parameter [3:0] GAPX     = 4'd4,
    parameter [3:0] VGAP     = 4'd3,
    parameter [7:0] PROJ_TH  = 8'd2,
    parameter [7:0] HOLD_N   = 8'd30,
    // 贴边拒绝：包围盒离画面边缘小于 EDGE_MARGIN 格就判为背景，直接拒绝。
    // 白墙/屏幕一定贴边，小船在画面中间不贴边 —— 这是小船区别于白墙的关键。
    parameter [3:0] EDGE_MARGIN = 4'd0,
    // 宽高比（形状约束）：要求 0.5 <= w/h <= 2.0，排除细长条和扁平板。
    // 小船实测 w/h≈1.15，落在范围内；细长杆/扁平纸会被拒。
    parameter        AR_EN = 1'b0
)(
    input  wire        I_clk,
    input  wire        I_rst_n,
    input  wire        I_sample,        // 8x8 网格采样拍
    input  wire        I_row_end_d1,    // 行末后 1 拍（非 sample 拍）
    input  wire        I_row_end_d2,    // 行末后 2 拍（非 sample 拍）
    input  wire        I_frame_end,     // 帧末拍
    input  wire        I_frame_end_d1,  // 帧末后 1 拍
    input  wire [7:0]  I_sx,            // 0..159
    input  wire [6:0]  I_sy,            // 0..89（row_end_d2 拍仍是当前行）
    input  wire        I_hit,           // 本格 halo 命中
    input  wire        I_core,          // 本格 core 命中
    input  wire [15:0] I_min_core,       // 全局最小 core 数（独立于 P24，不再耦合）

    output reg         O_valid,
    output reg  [8:0]  O_x0, O_x1,
    output reg  [7:0]  O_y0, O_y1,
    output reg         O_pass,          // 本帧过门限（frame_end_d1 拍更新）
    output reg  [10:0] O_gcore
);

    //=========================================================================
    // A + B：行内最长连续段
    //   A 段（sample 拍）：run 累加；不命中且 run 活跃 -> 结算 best
    //   B 段（row_end+1 拍）：row_end 拍若仍命中，run 会累加到含 x=159 这一格，
    //                        所以收段必须放到下一拍，此时 run_len 已稳定
    //=========================================================================
    reg        run_act;
    reg [7:0]  run_x0;
    reg [7:0]  run_len, run_core;
    reg [7:0]  best_x;
    reg [7:0]  best_len, best_core;

    // ★ 2026-10-30 行内统计：整行最左/最右/命中数
    //   为什么需要：红色 3D 打印框架是「回」字形镂空的，一行会被切成左右两段，
    //   只取「最长连续段」会导致框只套住一条竖边。
    //   所以先看整行密度，够密就取 [最左,最右]（镂空也算同一物体），
    //   密度不够（分散噪声）才退回最长段。
    reg [7:0]  l_min, l_max;
    reg [8:0]  l_cnt, l_ccnt;
    // 行结果（row_end+1 拍算出，row_end+2 拍给 band 合并用）
    reg        row_valid;
    reg [7:0]  row_x0, row_x1;
    reg [8:0]  row_ccnt;

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            run_act  <= 1'b0;
            run_x0   <= 8'd0;
            run_len  <= 8'd0;
            run_core <= 8'd0;
            best_x   <= 8'd0;
            best_len <= 8'd0;
            best_core<= 8'd0;
            l_min    <= 8'hFF;
            l_max    <= 8'd0;
            l_cnt    <= 9'd0;
            l_ccnt   <= 9'd0;
            row_valid<= 1'b0;
            row_x0   <= 8'd0;
            row_x1   <= 8'd0;
            row_ccnt <= 9'd0;
        end
        else if (I_sample) begin
            // 行内统计
            if (I_hit) begin
                if (l_cnt == 9'd0) begin
                    l_min <= I_sx;
                    l_max <= I_sx;
                end
                else begin
                    if (I_sx < l_min) l_min <= I_sx;
                    if (I_sx > l_max) l_max <= I_sx;
                end
                l_cnt  <= l_cnt  + 9'd1;
                l_ccnt <= l_ccnt + {8'd0, I_core};
            end
            // 最长连续段
            if (I_hit) begin
                if (!run_act) begin
                    run_act  <= 1'b1;
                    run_x0   <= I_sx;
                    run_len  <= 8'd1;
                    run_core <= {7'd0, I_core};
                end
                else begin
                    run_len  <= run_len  + 8'd1;
                    run_core <= run_core + {7'd0, I_core};
                end
            end
            else if (run_act) begin
                // 段自然结束：> 比较保持首个最大值（与 Python 的 max 一致）
                run_act <= 1'b0;
                if (run_len > best_len) begin
                    best_len  <= run_len;
                    best_x    <= run_x0;
                    best_core <= run_core;
                end
            end
        end
        else if (I_row_end_d1) begin
            // ① 段延伸到行末 -> 强制收段
            if (run_act) begin
                run_act <= 1'b0;
                if (run_len > best_len) begin
                    best_len  <= run_len;
                    best_x    <= run_x0;
                    best_core <= run_core;
                end
            end
            // ② 决定本行用哪一段
            //    bs_* = 「收段后」的 best（本拍 best_* 还没更新，所以要用组合值）
            if ((l_cnt >= {1'b0, PROJ_TH}) &&
                ({1'b0, l_cnt, 1'b0} >= ({1'b0, l_max} - {1'b0, l_min} + 9'd1))) begin
                // 整行填充率 >= 50% -> 用整行范围（镂空物体也能框全）
                row_valid <= 1'b1;
                row_x0    <= l_min;
                row_x1    <= l_max;
                row_ccnt  <= l_ccnt;
            end
            else if (bs_len >= PROJ_TH) begin
                // 密度不够 -> 退回最长连续段
                row_valid <= 1'b1;
                row_x0    <= bs_x;
                row_x1    <= bs_x + bs_len - 8'd1;
                row_ccnt  <= {1'b0, bs_core};
            end
            else begin
                row_valid <= 1'b0;
            end
            // ③ 清行内统计
            l_min <= 8'hFF;
            l_max <= 8'd0;
            l_cnt <= 9'd0;
            l_ccnt<= 9'd0;
        end
        else if (I_row_end_d2) begin
            // 清行内最长段。
            // ⚠ 必须在本块清，不能在 C/D/E 块清 —— 同一个 reg 被两个 always 块
            //   赋值会报 "net 'best_x[7]' is constantly driven from multiple places"。
            //   C 块在 row_end_d2 这一拍读 best_*（寄存器旧值，仍然有效）做 band 合并，
            //   同一拍末尾清零，互不冲突。
            best_len  <= 8'd0;
            best_x    <= 8'd0;
            best_core <= 8'd0;
        end
    end

    //=========================================================================
    // C + D + E：band 合并 / 帧末收 band / 门限输出
    //   三个分支互斥（row_end_d2 在行内空档、frame_end 在帧末、frame_end_d1 在其后）
    //   合成一个 always 块是因为 band_act / cand_* 被 C、D、E 共同写，
    //   分开写会报多驱动；用 else if 保证综合器按并行 mux 实现（路径取 max）
    //=========================================================================
    reg        band_act;
    reg [7:0]  bx0, bx1;
    reg [6:0]  by0, by1;
    reg [10:0] bcore;          // 11 位饱和计数
    reg [6:0]  last_y;

    reg        cand_valid;
    reg [10:0] cand_core;      // 11 位饱和计数
    reg [7:0]  cand_x0, cand_x1;
    reg [6:0]  cand_y0, cand_y1;

    reg [7:0]  miss;

    // 「收段后」的 best 组合值（row_end_d1 拍 best_* 尚未更新，必须用组合值）
    wire        bs_closing = I_row_end_d1 && run_act && (run_len > best_len);
    wire [7:0]  bs_len  = bs_closing ? run_len  : best_len;
    wire [7:0]  bs_x    = bs_closing ? run_x0   : best_x;
    wire [7:0]  bs_core = bs_closing ? run_core : best_core;
    // 段右端 = best_x + best_len - 1（9 位算，取低 8 位）
    wire [8:0] seg_hi = {1'b0, best_x} + {1'b0, best_len} - 9'd1;
    // 饱和加法：bcore + best_core，超过 2047 一律饱和
    wire [11:0] bc_sum = {1'b0, bcore} + {3'b0, row_ccnt};
    wire [10:0] bc_new = bc_sum[11] ? 11'h7FF : bc_sum[10:0];

    // 门限（组合，只在 frame_end_d1 拍采样）
    //  ⚠ K 倍必须写成「x + 2x」的加法/移位，不能写 DENS_K * x：
    //    4 位 x 9 位的乘法会被综合器推断成 DSP，三类各 2 个 = 6 个 DSP
    //    （全设计只有 32 个，实测确实被吃掉了 6 个）。
    //    写成加法后只用 9 位 ripple adder，判定结果完全一样。
    //  ★ 2026-10-30 支持 K=1/2/3：DENS_K 是 parameter，常量折叠会
    //    把没选中的分支优化掉，所以这里用 mux 选不会有额外资源。
    wire [7:0] gw = cand_x1 - cand_x0 + 8'd1;
    wire [7:0] gh = cand_y1 - cand_y0 + 8'd1;
    wire [10:0] gw_sh1 = {2'b0, gw, 1'b0};     // gw * 2
    wire [10:0] gh_sh1 = {2'b0, gh, 1'b0};     // gh * 2
    wire [10:0] gw_x3  = {3'b0, gw} + gw_sh1;  // gw * 3
    wire [10:0] gh_x3  = {3'b0, gh} + gh_sh1;  // gh * 3
    wire [10:0] kw = (DENS_K == 4'd2) ? gw_sh1 :
                     (DENS_K == 4'd1) ? {3'b0, gw} : gw_x3;
    wire [10:0] kh = (DENS_K == 4'd2) ? gh_sh1 :
                     (DENS_K == 4'd1) ? {3'b0, gh} : gh_x3;

    // 宽高比约束（AR_EN=0 时关闭）：2w>=h 且 w<=2h
    //  ⚠ 必须写成移位 {x,1'b0}，不能写 x+x —— 后者会被综合器识别成乘法，
    //    映射到 DSP（实测 DSP 从 26 涨到 29，时序也从 -3.9ns 恶化到 -5.1ns）。
    wire [8:0] w_x2 = {gw, 1'b0};
    wire [8:0] h_x2 = {gh, 1'b0};
    wire ar_ok = (AR_EN == 1'b0) ||
                 ((w_x2 >= {1'b0, gh}) && ({1'b0, gw} <= h_x2));

    // 贴边拒绝（EDGE_MARGIN=0 时关闭）
    wire edge_ok = (EDGE_MARGIN == 4'd0) ||
                   ((cand_x0 >= {4'd0, EDGE_MARGIN}) &&
                    (cand_x1 <= (8'd159 - {4'd0, EDGE_MARGIN})) &&
                    (cand_y0 >= {3'd0, EDGE_MARGIN}) &&
                    (cand_y1 <= (7'd89  - {3'd0, EDGE_MARGIN})));

    wire gate_ok = cand_valid                          &&
                   (cand_core >= {3'b0, MIN_CORE})     &&
                   (cand_core >= I_min_core[10:0])       &&
                   (cand_core >= kw) && (cand_core >= kh) &&
                   (gw >= MIN_W) && (gw <= MAX_W)      &&
                   ({1'b0, gh} >= {1'b0, MIN_H}) && ({1'b0, gh} <= {1'b0, MAX_H}) &&
                   edge_ok && ar_ok;

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            band_act   <= 1'b0;
            bx0 <= 8'd0;  bx1 <= 8'd0;
            by0 <= 7'd0;  by1 <= 7'd0;
            bcore      <= 11'd0;
            last_y     <= 7'd0;
            cand_valid <= 1'b0;
            cand_core  <= 11'd0;
            cand_x0 <= 8'd0;  cand_x1 <= 8'd0;
            cand_y0 <= 7'd0;  cand_y1 <= 7'd0;
            miss       <= 8'd0;
            O_valid    <= 1'b0;
            O_x0 <= 9'd0;  O_x1 <= 9'd0;
            O_y0 <= 8'd0;  O_y1 <= 8'd0;
            O_pass  <= 1'b0;
            O_gcore <= 11'd0;
        end
        //------------------------------------------------------------------
        // C：band 合并（row_end+2 拍）
        //------------------------------------------------------------------
        else if (I_row_end_d2) begin
            if (row_valid) begin
                if (!band_act) begin
                    // 开新 band
                    band_act <= 1'b1;
                    bx0 <= row_x0;
                    bx1 <= row_x1;
                    by0 <= I_sy;
                    by1 <= I_sy;
                    bcore <= {2'b0, row_ccnt};
                end
                else if (({1'b0, row_x0} <= ({1'b0, bx1} + {5'd0, GAPX})) &&
                         (({1'b0, row_x1} + {5'd0, GAPX}) >= {1'b0, bx0})) begin
                    // 横向重叠 -> 并入
                    if (row_x0 < bx0) bx0 <= row_x0;
                    if (row_x1 > bx1) bx1 <= row_x1;
                    by1   <= I_sy;
                    bcore <= bc_new;
                end
                else begin
                    // 不重叠 -> 收旧 band，开新 band
                    if (bcore > 11'd0) begin
                        if (!cand_valid || (bcore > cand_core)) begin
                            cand_valid <= 1'b1;
                            cand_core  <= bcore;
                            cand_x0 <= bx0;  cand_x1 <= bx1;
                            cand_y0 <= by0;  cand_y1 <= by1;
                        end
                    end
                    band_act <= 1'b1;
                    bx0 <= row_x0;
                    bx1 <= row_x1;
                    by0 <= I_sy;
                    by1 <= I_sy;
                    bcore <= {2'b0, row_ccnt};
                end
                last_y <= I_sy;
            end
            else if (band_act && (({1'b0, I_sy} - {1'b0, last_y}) > {4'd0, VGAP})) begin
                // 本行无有效段且空行超容忍 -> 收 band
                if (bcore > 11'd0) begin
                    if (!cand_valid || (bcore > cand_core)) begin
                        cand_valid <= 1'b1;
                        cand_core  <= bcore;
                        cand_x0 <= bx0;  cand_x1 <= bx1;
                        cand_y0 <= by0;  cand_y1 <= by1;
                    end
                end
                band_act <= 1'b0;
            end
            // 注：行内最长段 best_* 的清零放在 A+B 块（I_row_end_d2 那一拍），
            //     不能在这里清 —— 否则 best_* 会被两个 always 块驱动，报多驱动。
        end
        //------------------------------------------------------------------
        // D：帧末收 band（frame_end 拍）
        //------------------------------------------------------------------
        else if (I_frame_end) begin
            if (band_act && (bcore > 11'd0)) begin
                if (!cand_valid || (bcore > cand_core)) begin
                    cand_valid <= 1'b1;
                    cand_core  <= bcore;
                    cand_x0 <= bx0;  cand_x1 <= bx1;
                    cand_y0 <= by0;  cand_y1 <= by1;
                end
            end
            band_act <= 1'b0;
        end
        //------------------------------------------------------------------
        // E：门限判定 + 帧间保持 + 输出（frame_end+1 拍）
        //------------------------------------------------------------------
        else if (I_frame_end_d1) begin
            O_pass  <= gate_ok;
            O_gcore <= cand_core;
            if (gate_ok) begin
                O_valid <= 1'b1;
                O_x0 <= {1'b0, cand_x0};
                O_x1 <= {1'b0, cand_x1};
                O_y0 <= {1'b0, cand_y0};
                O_y1 <= {1'b0, cand_y1};
                miss <= 8'd0;
            end
            else if (miss < HOLD_N) begin
                miss <= miss + 8'd1;
            end
            else begin
                O_valid <= 1'b0;
            end
            // 清帧级候选
            cand_valid <= 1'b0;
            cand_core  <= 11'd0;
        end
    end

endmodule


